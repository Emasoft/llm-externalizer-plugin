# Row 97 (fix-queue): the writer (benchmark/pick.ts writeDynamicProfileSection,
# both call sites) stamps GENERATED_MARKER as a yaml `commentBefore` -- a
# comment line ABOVE the `<name>:` key, indented to match it (2 spaces under
# `profiles:`), never a same-line trailing comment. The old pattern
# (`^name:\s*#\s*<--...-->`, anchored at column 0) could never match that
# real on-disk shape -- it required the marker AFTER the key on the SAME
# line, unindented. Verified against a real generated settings.yaml:
#   "  # <-- do not touch, generated by llm-ext -->\n  free:\n"
# The fixed pattern matches the marker comment line followed by the
# (indented) key line, and captures the key name.
# Adversarial-review follow-up on 235f4f5: the marker TEXT below is no
# longer a second hand-copied literal -- _load_generated_marker() reads it
# from its actual definition site (config.ts) at import time, so a future
# rename of the writers string cannot silently make this regex match
# nothing on disk again, which is exactly how the bug above shipped.
_GENERATED_SECTION_RE: re.Pattern[str] | None = None
_GENERATED_SECTION_RE_ERROR: str | None = None


def _generated_dynamic_sections(cfg_dir: Path) -> set[str]:
    """Top-level settings.yaml keys the maintainer marked as generated.

    Reads the isolated copy under ``cfg_dir`` (never REAL_SETTINGS) -- the
    maintainer only writes there because every spawn in this harness passes
    ISOLATED_ENV (fix-queue row 81, TRDD-90DM5YHO).

    Returns an empty set (never raises) when the marker regex itself could
    not be built -- the caller, phase_dynamic_sections, checks
    _get_generated_section_re() itself up front and reports that failure as
    its own FAIL rows, so a bare empty set here would otherwise be
    misread as "settings.yaml has no generated sections" instead of "the
    marker lookup failed".
    """
    settings = cfg_dir / "settings.yaml"
    if not settings.exists():
        return set()
    pattern = _get_generated_section_re()
    if pattern is None:
        return set()
    return set(pattern.findall(settings.read_text(encoding="utf-8")))

def _marker_drift_note(cfg_dir: Path, got: set[str]) -> str:
    """Extra hint appended to a generated-sections FAIL detail when the
    regex found nothing at all.

    Row 97 follow-up: a `profiles:` key present with zero marked sections
    almost always means the writer's marker string diverged from
    _GENERATED_SECTION_RE's compiled copy (the exact silent-[] failure this
    fix chain exists to catch) rather than "no profile was ever
    generated" -- call that out explicitly so a bare FAIL is not misread
    as the latter.
    """
    if got:
        return ""
    settings = cfg_dir / "settings.yaml"
    if settings.exists() and "profiles:" in settings.read_text(encoding="utf-8"):
        return (
            " -- settings.yaml has a 'profiles:' key but the marker regex "
            "matched none of them: the writer's marker text may have drifted "
            "from _GENERATED_SECTION_RE's compiled copy"
        )
    return ""


def _model_id_from_output(text: str) -> str | None:
    """Best-effort extraction of the answering model id from CLI output."""
    try:
        obj = json.loads(text.strip())
        if isinstance(obj, dict):
            for key in ("model", "model_id", "answeredBy", "id"):
                if isinstance(obj.get(key), str):
                    return obj[key]
    except (json.JSONDecodeError, ValueError):
        pass
    for line in text.splitlines():
        s = line.strip()
        if ":free" in s:
            for tok in s.replace(",", " ").replace('"', " ").split():
                if "/" in tok and ":free" in tok:
                    return tok
    return None


