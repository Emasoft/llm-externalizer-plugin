def main() -> int:
    started = datetime.now()
    live = os.environ.get("DOGFOOD_LIVE") == "1"
    h = Harness()

    real_settings_before = _sha256_or_none(REAL_SETTINGS)
    global ISOLATED_ENV
    ISOLATED_ENV = _setup_isolated_env()

    # Sanity: the CLI entry points must exist before we do anything.
    for label, p in (("bin/llm-ext", LLM_EXT), ("bin/llm-ext-benchmark", LLM_EXT_BENCH)):
        if not p.exists():
            h.add("build", label, FAIL, f"{label} present", f"missing: {p}")

    if not LLM_EXT.exists():
        table = render_table(h.checks)
        print(table)
        report = write_report(h.checks, table, started, live)
        print(f"\nReport: {report}")
        _print_worktree_status()
        return 1

    built = phase_build(h)
    if built:
        verbs, groups = phase_top_help(h)
        if verbs:
            phase_per_verb_help(h, verbs, groups)
        phase_discover(h)
        phase_benchmark(h)
        phase_readonly_tools(h)
        phase_command_audit(h, verbs)
    else:
        # Build failed: skip the CLI phases (same root cause), but still audit
        # the static command/skill files. Verb resolution is deferred (catalog
        # unavailable), not failed.
        h.add("cli", "(skipped)", SKIP, "CLI phases skipped because the build failed", "")
        phase_command_audit(h, [], catalog_available=False)

    # Skill audit, the sweep and live smoke do not depend on the build.
    phase_skill_audit(h)
    phase_promise_vs_code_sweep(h)
    phase_live_smoke(h)
    # Unconditional (no DOGFOOD_LIVE gate): the DEFAULT first-run check, per
    # 4i (review of 9e6fbd3) -- see phase_dynamic_sections' own docstring.
    phase_dynamic_sections(h)

    table = render_table(h.checks)
    print(table)
    counts = summary_counts(h.checks)
    print(
        f"\n{counts[PASS]} PASS · {counts[FAIL]} FAIL · {counts[WARN]} WARN · {counts[SKIP]} SKIP "
        f"({len(h.checks)} checks)"
    )
    report = write_report(h.checks, table, started, live)
    print(f"Report: {report}")
    # Always visible, pass or fail: phase_build's determinism gate already
    # fails loud on a dist/ drift, but a dirty tree from any OTHER cause
    # (a generated file outside dist/, an interrupted run) would otherwise
    # only show up if someone happened to run `git status` by hand.
    _print_worktree_status()

    # Canary (TRDD-90DM5YHO, fix-queue row 81): the real settings.yaml must be
    # byte-identical to what it was before this run. Every spawn above went
    # through ISOLATED_ENV's throwaway LLM_EXT_CONFIG_DIR, so nothing this
    # harness ran should have been able to touch the original file — this is
    # the harness's own guard against a regression reintroducing that leak,
    # not a plugin test.
    real_settings_after = _sha256_or_none(REAL_SETTINGS)
    if real_settings_before != real_settings_after:
        print(
            f"\nCANARY FAILED: {REAL_SETTINGS} changed during this run "
            f"({real_settings_before} -> {real_settings_after}). "
            "A spawned CLI call escaped LLM_EXT_CONFIG_DIR isolation."
        )
        return 1

    return 1 if h.failed else 0


