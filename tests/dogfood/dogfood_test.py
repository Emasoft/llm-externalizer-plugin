def _sha256_or_none(p: Path) -> str | None:
    """sha256 of a file's bytes, or None if it does not exist."""
    if not p.exists():
        return None
    return hashlib.sha256(p.read_bytes()).hexdigest()


def _setup_isolated_env(*, seed: bool = True) -> dict[str, str]:
    """Create a throwaway LLM_EXT_CONFIG_DIR and return the env dict every
    CLI spawn in this harness must use.

    Seeded with a READ-ONLY copy of the real settings.yaml (if present) so
    phases that need a real profile/credential still see one — the CLI then
    reads and writes only inside the copy, never the original. That copy may
    carry a literal `providers[].api_key` from the real file. The dir is
    removed at process exit unless DOGFOOD_KEEP_CFG=1 (debugging escape hatch
    that leaves the copy, credential included, on disk).

    ``seed=False`` (adversarial-review follow-up on 235f4f5, generated-
    sections fresh-install check) skips the copy entirely, returning a
    genuinely empty config dir -- the ONLY way to test the release's real
    "a brand-new install bootstraps all three dynamic sections from one bare
    `discover`" promise, which a dir pre-seeded with a real settings.yaml
    (whose `active:` may point elsewhere) cannot exercise.
    """
    # dir="/tmp": a bare mkdtemp() lands under $TMPDIR (/var/folders/.../T on
    # macOS), which getConfigDir()'s path guard (scripts/llm-ext/src/config.ts)
    # refuses as outside its home/private-tmp allowlist -- every CLI spawn in
    # the harness then failed with "outside allowed paths" (fix-queue 85).
    cfg_dir = Path(tempfile.mkdtemp(prefix="dogfood-cfg-", dir="/tmp"))
    if seed and REAL_SETTINGS.exists():
        shutil.copy(REAL_SETTINGS, cfg_dir / "settings.yaml")
    print(f"Isolated LLM_EXT_CONFIG_DIR: {cfg_dir}")
    if os.environ.get("DOGFOOD_KEEP_CFG") != "1":
        atexit.register(shutil.rmtree, cfg_dir, True)
    return {**os.environ, "LLM_EXT_CONFIG_DIR": str(cfg_dir), "LLM_EXT_INSTALL_RULE": "0"}


def main_repo_root() -> Path:
    """Resolve the main repo root (worktree-safe).

    `git worktree list` always lists the primary working tree first, even when
    called from a linked worktree, so reports land in one place regardless of
    where the harness runs. Falls back to PROJECT_ROOT if git is unavailable.
    """
    try:
        out = subprocess.run(
            ["git", "worktree", "list"],
            cwd=str(PROJECT_ROOT),
            capture_output=True,
            text=True,
            timeout=15,
        )
        if out.returncode == 0 and out.stdout.strip():
            first = out.stdout.splitlines()[0].split()[0]
            return Path(first)
    except (OSError, subprocess.SubprocessError):
        pass
    return PROJECT_ROOT


