def phase_build(h: Harness) -> bool:
    """Compile the engine so the wrappers can run dist/llm-ext.js + dist/benchmark.js.

    `bin/llm-ext` runs launcher.mjs, which runs `scripts/llm-ext/dist/llm-ext.js`;
    `bin/llm-ext-benchmark` runs `scripts/llm-ext/dist/benchmark.js` (both verified
    by reading the wrapper scripts). Without a build every CLI phase fails for the
    same root cause, so this gate runs first and stops the CLI phases (but not the
    static file audits) on failure. `npm run build` = `tsc --noEmit && esbuild` per
    scripts/llm-ext/package.json.
    """
    dist_dir = ENGINE_DIR / "dist"
    # Determinism gate (fix-queue row 87): a source commit whose dist was not
    # rebuilt used to leave scripts/llm-ext/dist/*.js dirty with an uncontrolled
    # bundle and nothing reported it (154d083, 2026-09-17) -- `npm run build`
    # exiting 0 says nothing about whether the committed dist matched what a
    # fresh build produces. Hash dist before and after so any drift fails the
    # phase instead of shipping silently, the way P6d used to check by hand.
    before_hashes = _dist_hashes(dist_dir)
    res = run(["npm", "run", "build"], cwd=ENGINE_DIR, timeout=BUILD_TIMEOUT)
    if res.code != 0:
        h.add(
            "build",
            "npm run build",
            FAIL,
            "compile the engine (tsc --noEmit && esbuild)",
            _evidence(res, 2500),
        )
        return False
    after_hashes = _dist_hashes(dist_dir)
    if after_hashes != before_hashes:
        changed = sorted(
            rel for rel in set(before_hashes) | set(after_hashes) if before_hashes.get(rel) != after_hashes.get(rel)
        )
        h.add(
            "build",
            "npm run build",
            FAIL,
            "committed dist/ must match a fresh build (determinism gate)",
            "dist/ changed by the build:\n"
            + "\n".join(changed)
            # A third cause is named because a second machine with a different
            # esbuild/Node would otherwise "fix" this by committing its own
            # bundle over the release one instead of investigating why it drifted.
            + "\nHEAD's dist is stale, the build is non-deterministic, or your "
            "toolchain differs from the one that committed dist: rebuild and "
            "commit dist only if src changed",
        )
        return False
    missing = [str(p) for p in (CLI_BUNDLE, BENCH_BUNDLE) if not p.exists()]
    if missing:
        h.add(
            "build",
            "npm run build",
            FAIL,
            "compile the engine (tsc --noEmit && esbuild)",
            "build exited 0 but expected artifact(s) missing:\n" + "\n".join(missing),
        )
        return False
    h.add(
        "build",
        "npm run build",
        PASS,
        "compile the engine -> dist/llm-ext.js + dist/benchmark.js",
    )
    return True


