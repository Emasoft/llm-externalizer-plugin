# Phase 8b — promise-vs-code sweep: directive 4 bans cross-profile fallback
# --------------------------------------------------------------------------- #


# A quote-delimited span on a single source line: "...", '...', or `...`.
# Used only to decide whether a PROMISE_VS_CODE_PATTERNS hit sits inside a
# string literal (a comment/doc-string NAMING the banned identifier) rather
# than in live code that USES it -- see _hit_in_string_literal below.
_STRING_LITERAL_SPAN = re.compile(r'"[^"\n]*"|\'[^\'\n]*\'|`[^`\n]*`')


def _hit_in_string_literal(line: str, start: int, end: int) -> bool:
    """True iff `line[start:end]` (the matched pattern) falls entirely
    inside one of the line's quoted spans."""
    return any(
        span.start() <= start and end <= span.end()
        for span in _STRING_LITERAL_SPAN.finditer(line)
    )


def phase_promise_vs_code_sweep(h: Harness) -> None:
    """Fail if a banned cross-profile-fallback identifier still exists.

    A doc sweep can't see this -- it's a code property, not prose -- so the
    harness greps the TS source itself for PROMISE_VS_CODE_PATTERNS, LINE by
    LINE (4i, review of 9e6fbd3: a whole-file allow-list let an entire file
    off the hook even on a POSITIVE-assertion line; a line-shaped allowance
    cannot). A hit is only tolerated on a line that ALSO contains one of
    PROMISE_VS_CODE_ABSENCE_MARKERS -- i.e. the line itself asserts the
    identifier's absence, not merely names it; every other hit, test file or
    not, means the promise isn't kept in code yet.

    C2c-ENV (TRDD-OE27RD7I, fix-queue row 94): the `// absence-assert`
    escape hatch is narrower than the other two markers -- `not.toContain`
    and `toBeUndefined` are vitest assertion calls that can only appear in
    live test CODE already asserting absence, but a bare `// absence-assert`
    comment can sit on ANY line, including a live call site that merely
    happens to share a line with an unrelated trailing comment. So it is
    accepted ONLY when (a) the file is a `*.test.ts` file -- a non-test file
    has no test assertion to excuse, a stray comment there is not one -- AND
    (b) the matched identifier itself sits inside a string literal on that
    line (a doc-string/description NAMING the pattern), never in live,
    executable code that USES it.

    Row 98(4d): PROMISE_VS_CODE_ABSENCE_MARKERS used to be a dead tuple --
    the two vitest-call markers were hard-coded literals below, independent
    of the tuple, and only the ESCAPE HATCH string was ever compared against
    it (nowhere, in fact: the old code compared against the literal
    `"// absence-assert"` too). The loop below now iterates the tuple itself
    for the plain markers, and keys the escape-hatch special case off the
    same tuple entry rather than a second hard-coded copy of it -- so a
    future edit to the tuple actually changes behaviour instead of silently
    doing nothing.
    """
    src_dir = ENGINE_DIR / "src"
    targets = sorted(src_dir.rglob("*.ts")) + sorted(ENGINE_DIR.glob("*.mjs"))
    pattern = re.compile("|".join(re.escape(p) for p in PROMISE_VS_CODE_PATTERNS))
    escape_hatch = "// absence-assert"
    plain_markers = [m for m in PROMISE_VS_CODE_ABSENCE_MARKERS if m != escape_hatch]
    offenders: list[str] = []
    for f in targets:
        rel = f.relative_to(ENGINE_DIR).as_posix()
        is_test_file = f.name.endswith(".test.ts")
        text = f.read_text(encoding="utf-8", errors="ignore")
        for lineno, line in enumerate(text.splitlines(), start=1):
            hit = pattern.search(line)
            if not hit:
                continue
            if any(marker in line for marker in plain_markers):
                continue
            if (
                escape_hatch in PROMISE_VS_CODE_ABSENCE_MARKERS
                and escape_hatch in line
                and is_test_file
                and _hit_in_string_literal(line, hit.start(), hit.end())
            ):
                continue
            offenders.append(f"{rel}:{lineno}: {hit.group(0)!r}")
    desc = (
        "every PROMISE_VS_CODE_PATTERNS hit is on a line asserting absence "
        "(not.toContain|toBeUndefined|// absence-assert)"
    )
    if offenders:
        h.add(
            "sweep",
            "promise-vs-code",
            FAIL,
            desc,
            "cross-profile fallback still present:\n" + "\n".join(offenders),
        )
    else:
        h.add("sweep", "promise-vs-code", PASS, desc)

def _load_generated_marker() -> str:
    """Read the literal generated-section marker text from its actual
    definition site instead of hand-copying it into this regex a second
    time (adversarial-review follow-up on 235f4f5, row 97): a second,
    hard-coded literal is exactly the class of bug that made the OLD regex
    silently match nothing on disk -- a future rename of the writer's
    string would do the same to a hand-copied copy here, with no signal
    beyond "sections FAIL" until someone reads both files side by side.

    `benchmark/pick.ts` only IMPORTS `GENERATED_MARKER`
    (`import { ..., GENERATED_MARKER, ... } from "../config.js"`) and
    re-exports it; the string literal itself is defined once, in
    config.ts -- that is the file this reads at runtime.

    Matches either quote style (`"..."` or `'...'`) so a cosmetic
    quote-convention change in config.ts (review follow-up: the original
    version only matched double quotes) does not itself trip the
    RuntimeError below -- only a genuine rename/removal of the constant
    should.
    """
    config_ts = ENGINE_DIR / "src" / "config.ts"
    text = config_ts.read_text(encoding="utf-8")
    # ponytail: grepping a source literal out of config.ts is a ceiling, not
    # a plan -- it only survives while GENERATED_MARKER stays a plain
    # `NAME = "..."` one-liner. A template literal or a computed value (e.g.
    # `GENERATED_MARKER = PREFIX + "..."`) would make this regex match
    # nothing with no error at all (find() returns None -> RuntimeError,
    # loud) or, worse, match a stale substring (silent, wrong). Upgrade path
    # if that ever happens: evaluate the module for real (spawn a tiny
    # `node -e` that imports config.js and prints GENERATED_MARKER) instead
    # of reading its source text.
    m = re.search(r"GENERATED_MARKER\s*=\s*[\"'](.+?)[\"']", text)
    if not m:
        raise RuntimeError(
            f"could not find the GENERATED_MARKER definition in {config_ts} -- "
            "the writer's marker string, or its source file, moved; update "
            "_load_generated_marker() in dogfood_test.py to match"
        )
    return m.group(1)

def _get_generated_section_re() -> re.Pattern[str] | None:
    """Lazily compile _GENERATED_SECTION_RE on first use, caching the result
    (or the failure) in the two module globals below.

    Adversarial-review follow-up on 7679b1e: the two globals below used to
    be a single line, ``_GENERATED_SECTION_RE = re.compile(... +
    re.escape(_load_generated_marker()) + ...)``, evaluated at MODULE IMPORT
    TIME -- so a missing/renamed GENERATED_MARKER raised RuntimeError before
    a single one of the ~110 other dogfood checks could run at all. Moving
    the lookup here, called lazily from phase_dynamic_sections, means a
    drifted marker now fails loudly as two FAIL rows under that phase's
    own labels instead of killing the whole harness.
    """
    global _GENERATED_SECTION_RE, _GENERATED_SECTION_RE_ERROR
    if _GENERATED_SECTION_RE is not None or _GENERATED_SECTION_RE_ERROR is not None:
        return _GENERATED_SECTION_RE
    try:
        marker = _load_generated_marker()
    except RuntimeError as exc:
        _GENERATED_SECTION_RE_ERROR = str(exc)
        return None
    _GENERATED_SECTION_RE = re.compile(
        r"^[ \t]*#\s*" + re.escape(marker) + r"\s*\n[ \t]*([A-Za-z0-9_-]+):",
        re.MULTILINE,
    )
    return _GENERATED_SECTION_RE


