def _evidence(res: RunResult, limit: int = 1500) -> str:
    return (
        f"exit={res.code}{' (TIMED OUT)' if res.timed_out else ''}\n"
        f"stdout:\n{res.out.strip()[:limit]}\n"
        f"stderr:\n{res.err.strip()[:limit]}"
    )


def _dist_hashes(dist_dir: Path) -> dict[str, str]:
    """sha256 of every file under dist_dir, keyed by its path relative to
    dist_dir. Empty dict when the directory does not exist (first-ever build)."""
    hashes: dict[str, str] = {}
    if not dist_dir.is_dir():
        return hashes
    for p in sorted(dist_dir.rglob("*")):
        if p.is_file():
            hashes[str(p.relative_to(dist_dir))] = hashlib.sha256(p.read_bytes()).hexdigest()
    return hashes


