def write_report(checks: list[Check], table: str, started: datetime, live: bool) -> Path:
    root = main_repo_root()
    report_dir = root / "reports" / "dogfood"
    report_dir.mkdir(parents=True, exist_ok=True)
    ts = started.astimezone().strftime("%Y%m%d_%H%M%S%z")
    report = report_dir / f"{ts}-dogfood.md"

    counts = summary_counts(checks)
    lines: list[str] = []
    lines.append("# llm-externalizer dogfood report")
    lines.append("")
    lines.append(f"Generated: {started.astimezone().isoformat()}")
    lines.append(f"Mode: {'LIVE (DOGFOOD_LIVE=1)' if live else 'default ($0, offline / read-only)'}")
    lines.append(f"Project root: `{PROJECT_ROOT}`")
    lines.append("")
    lines.append(
        f"Totals: {counts[PASS]} PASS · {counts[FAIL]} FAIL · {counts[WARN]} WARN · {counts[SKIP]} SKIP "
        f"({len(checks)} checks)"
    )
    lines.append("")
    lines.append("## Result table")
    lines.append("")
    lines.append("```")
    lines.append(table)
    lines.append("```")
    lines.append("")

    attn = [c for c in checks if c.status in (FAIL, WARN)]
    lines.append("## Findings (FAIL / WARN)")
    lines.append("")
    if not attn:
        lines.append("_None — all checks passed or were skipped._")
        lines.append("")
    else:
        for c in attn:
            lines.append(f"### [{c.status}] {c.surface} · {c.name}")
            lines.append("")
            lines.append(f"- Check: {c.description}")
            if c.detail:
                lines.append("- Evidence:")
                lines.append("")
                lines.append("```")
                lines.append(c.detail.rstrip())
                lines.append("```")
            lines.append("")

    lines.append("## All checks")
    lines.append("")
    for c in checks:
        lines.append(f"- [{c.status}] `{c.surface}` · `{c.name}` — {c.description}")
    lines.append("")

    report.write_text("\n".join(lines), encoding="utf-8")
    return report


def _print_worktree_status() -> None:
    """Print `git status --porcelain` for the repo at the very end of the run.

    `npm run build` (phase_build) writes into scripts/llm-ext/dist/; the
    determinism gate above fails loud on that, but a human skimming a PASS
    run still could not tell the tree is dirty for some OTHER reason (a
    generated file outside dist/, an interrupted run) unless it is shown
    every time, not only on failure.
    """
    res = subprocess.run(
        ["git", "-C", str(PROJECT_ROOT), "status", "--porcelain"],
        capture_output=True,
        text=True,
        timeout=30,
    )
    print("\nworking tree after run:")
    # "(clean)" on a git error (missing binary, non-repo root) was the one
    # dishonest output here: empty stdout from a FAILED command looks
    # identical to empty stdout from a clean tree unless returncode is checked.
    if res.returncode != 0:
        print(f"git status failed (exit {res.returncode}): {res.stderr.strip()}")
    else:
        print(res.stdout.rstrip() or "(clean)")


