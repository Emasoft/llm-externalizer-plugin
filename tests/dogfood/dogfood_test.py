def phase_dynamic_sections(h: Harness) -> None:
    """Assert settings.yaml carries every EXPECTED_DYNAMIC_PROFILE_NAMES section.

    Moved OUT of phase_live_smoke's DOGFOOD_LIVE=1 gate (4i, review of
    9e6fbd3): that gate made this a check nobody's default run ever
    executed -- a release could ship with it permanently SKIPPED and nobody
    would notice.

    Adversarial-review follow-up on 235f4f5 (row 97): a single check that
    spawned `discover --profile <name>` once per dynamic name only proved
    overrideActiveProfile writes the section it's pointed at -- never the
    release's real promise that a FRESH install (ensureSettingsExist's
    first-run branch, index.ts) ships all three sections from ONE bare
    `discover` with no --profile at all. Split into two separately
    labelled checks so each promise has its own PASS/FAIL:

    (a) "generated-sections (fresh install)" -- LOAD-BEARING. Runs against
        a brand-new, unseeded LLM_EXT_CONFIG_DIR (_setup_isolated_env's
        seed=False -- never copies REAL_SETTINGS), so there is no
        pre-existing settings.yaml whose `active:` could point away from a
        dynamic profile, and no residue any earlier phase in this same
        process could have left behind. A single bare `discover` is the
        only invocation this check makes. It also asserts the release's
        OTHER fresh-install promise -- exactly one ``active: free`` line --
        which the three-section count alone cannot catch (a settings.yaml
        with all three sections but a duplicated or missing `active:` line
        would still count as "3 of 3 sections" and slip past it).
    (b) "generated-sections (seeded active)" -- the original per-profile
        `--profile <name>` loop, against the harness's SHARED ISOLATED_ENV
        (which _setup_isolated_env seeds with a copy of the real
        settings.yaml, if one exists on this machine). Covers a real
        settings.yaml whose `active:` points at some OTHER, non-dynamic
        profile: there, a single bare `discover` would bootstrap nothing
        for free/paid/local, so `--profile <name>` forces the write for
        each one independently. Because it shares ISOLATED_ENV with every
        other phase, a PASS here does not by itself prove THIS loop wrote
        the sections -- phase_live_smoke (DOGFOOD_LIVE=1) runs earlier in
        main() and may already have populated the same settings.yaml
        before this loop ever spawns; either way the assertion is the
        same (adversarial review of this very commit, unresolved without
        reading main()'s full phase order -- disclosed, not fixed here).
        Check (a) above carries no such ambiguity.

    `discover` is in `RECONCILE_SKIP_TOOLS` (scripts/llm-ext/src/index.ts):
    it never triggers the reconcile-driven detector/benchmark spawn, so
    the four `discover` calls this phase makes (one for (a), three for
    (b)) leave no grandchild process behind -- the dogfood harness run's
    own process-table check depends on that membership holding.
    """
    if ISOLATED_ENV is None:
        detail = "ISOLATED_ENV was never set up (main() must call _setup_isolated_env() first)"
        h.add(
            "sweep",
            "generated-sections (fresh install)",
            FAIL,
            "settings.yaml carries every EXPECTED_DYNAMIC_PROFILE_NAMES generated section on a fresh install",
            detail,
        )
        h.add(
            "sweep",
            "generated-sections (seeded active)",
            FAIL,
            "settings.yaml carries every EXPECTED_DYNAMIC_PROFILE_NAMES generated section via --profile",
            detail,
        )
        return

    # Adversarial-review follow-up (7679b1e): _get_generated_section_re()
    # used to be a module-level `re.compile(... + _load_generated_marker()
    # + ...)` line, so a missing/renamed GENERATED_MARKER raised
    # RuntimeError at IMPORT TIME and killed all ~110 dogfood checks, not
    # just these two. Checking it here, once, up front, turns that same
    # loud signal into two FAIL rows under this phase's own labels and lets
    # every other phase in main() still run. Side effect (own review):
    # this also skips the `discover` spawns below entirely on a marker
    # failure -- a real behaviour change from the old code, which still
    # ran `discover` even though it could never parse the result; accepted
    # because a broken marker regex makes both spawns pointless anyway.
    if _get_generated_section_re() is None:
        detail = f"could not compile the generated-section marker regex: {_GENERATED_SECTION_RE_ERROR}"
        h.add(
            "sweep",
            "generated-sections (fresh install)",
            FAIL,
            "settings.yaml carries every EXPECTED_DYNAMIC_PROFILE_NAMES generated section on a fresh install",
            detail,
        )
        h.add(
            "sweep",
            "generated-sections (seeded active)",
            FAIL,
            "settings.yaml carries every EXPECTED_DYNAMIC_PROFILE_NAMES generated section via --profile",
            detail,
        )
        return

    want = set(EXPECTED_DYNAMIC_PROFILE_NAMES)
    # The release's second fresh-install promise: not just the three
    # generated sections, but the bootstrap picking exactly one active
    # profile (`free`) -- a settings.yaml with a duplicated or missing
    # `active:` line would still count "3 of 3 sections" above, so this
    # needs its own, separate regex check on the same fresh dir.
    # fix-queue row 103: the old single regex (`^active:\s*free\s*$`) false-
    # FAILed on the spellings a human is likely to hand-edit (`active: "free"`,
    # or a trailing `# comment`) -- not a claim to cover every valid YAML
    # spelling. Split into two: one that finds every top-level `active:` key
    # (any value, for the "exactly one" count) and one that checks the found
    # line's value is `free`, optionally quoted, with an optional trailing
    # comment.
    # fix-queue row 103b: `#` starts a YAML comment only after whitespace (or
    # at line start) -- `active: free#x` is the scalar "free#x", not "free"
    # with a comment, so the old `(?:#.*)?` (no separator required) wrongly
    # PASSed it. `(?:\s+#.*)?` requires that whitespace.
    # ponytail: regex-based YAML scalar parsing, not a real YAML reader (no
    # block scalars, no flow maps) -- this harness carries no PyYAML
    # dependency; swap for `yaml.safe_load()` if settings.yaml ever needs a
    # value shape this can't parse.
    active_key_re = re.compile(r"^active:.*$", re.MULTILINE)
    active_free_re = re.compile(r"""^active:\s*(?:free|"free"|'free')\s*(?:\s+#.*)?$""")

    # (a) fresh install -- a brand-new, unseeded config dir so no
    # pre-existing `active:` value can steer the write; this is the check
    # that actually proves the release's "a fresh install ships all three
    # sections" claim (the seeded loop below cannot, by construction).
    fresh_env = _setup_isolated_env(seed=False)
    fresh_cfg_dir = Path(fresh_env["LLM_EXT_CONFIG_DIR"])
    desc_a = "settings.yaml carries every EXPECTED_DYNAMIC_PROFILE_NAMES generated section on a fresh install"
    res_a = run(["node", str(LLM_EXT), "discover"], cwd=PROJECT_ROOT, env=fresh_env)
    if res_a.code != 0:
        # A non-zero exit means `discover` itself failed -- FAIL this check
        # under its own label instead of silently reading whatever (if
        # anything) landed on disk, which would misreport a crashed CLI as
        # "no sections generated yet".
        h.add(
            "sweep",
            "generated-sections (fresh install)",
            FAIL,
            desc_a,
            f"bare `discover` exited {res_a.code}:\n{_evidence(res_a)}",
        )
    else:
        got_a = _generated_dynamic_sections(fresh_cfg_dir)
        if got_a != want:
            h.add(
                "sweep",
                "generated-sections (fresh install)",
                FAIL,
                desc_a,
                f"expected {sorted(want)}, got {sorted(got_a)} in {fresh_cfg_dir / 'settings.yaml'}"
                + _marker_drift_note(fresh_cfg_dir, got_a),
            )
        else:
            # Second promise, same fresh dir: exactly one `active:` key (any
            # spelling) whose value is `free` -- checked only once the
            # section count already passed, so a single FAIL never reports
            # two unrelated causes at once.
            fresh_text = (fresh_cfg_dir / "settings.yaml").read_text(encoding="utf-8")
            active_key_lines = active_key_re.findall(fresh_text)
            if len(active_key_lines) == 1 and active_free_re.match(active_key_lines[0]):
                h.add("sweep", "generated-sections (fresh install)", PASS, desc_a, f"generated: {sorted(got_a)}")
            elif len(active_key_lines) != 1:
                h.add(
                    "sweep",
                    "generated-sections (fresh install)",
                    FAIL,
                    desc_a,
                    f"expected exactly one 'active:' key, found {len(active_key_lines)} in "
                    f"{fresh_cfg_dir / 'settings.yaml'}",
                )
            else:
                h.add(
                    "sweep",
                    "generated-sections (fresh install)",
                    FAIL,
                    desc_a,
                    "expected 'active: free' (optionally quoted, with an optional trailing "
                    f"comment), found {active_key_lines[0]!r} in {fresh_cfg_dir / 'settings.yaml'}",
                )

    # (b) seeded active -- the original per-profile loop, against the
    # harness's shared (possibly real-settings-seeded) ISOLATED_ENV.
    cfg_dir = Path(ISOLATED_ENV["LLM_EXT_CONFIG_DIR"])
    desc_b = "settings.yaml carries every EXPECTED_DYNAMIC_PROFILE_NAMES generated section via --profile"
    # NIT follow-up (7679b1e): `break`-ing on the first non-zero exit hid
    # whether the OTHER two names would also fail -- run all three
    # regardless, collect every non-zero exit, and FAIL once naming all of
    # them, so one bad run doesn't hide a second, independent one.
    failures: list[str] = []
    for name in EXPECTED_DYNAMIC_PROFILE_NAMES:
        res_b = llm_ext(["discover", "--profile", name])
        if res_b.code != 0:
            failures.append(f"`discover --profile {name}` exited {res_b.code}:\n{_evidence(res_b)}")
    if failures:
        # Same rule as (a): a spawn failure FAILS this check with its own
        # label -- it must never be swallowed and read as "no section for
        # this profile yet".
        h.add("sweep", "generated-sections (seeded active)", FAIL, desc_b, "\n".join(failures))
    else:
        got_b = _generated_dynamic_sections(cfg_dir)
        if got_b == want:
            h.add("sweep", "generated-sections (seeded active)", PASS, desc_b, f"generated: {sorted(got_b)}")
        else:
            h.add(
                "sweep",
                "generated-sections (seeded active)",
                FAIL,
                desc_b,
                f"expected {sorted(want)}, got {sorted(got_b)} in {cfg_dir / 'settings.yaml'} "
                "(no live dispatch ran, or D2 has not landed yet, or both -- see the check's docstring)"
                + _marker_drift_note(cfg_dir, got_b),
            )


# --------------------------------------------------------------------------- #
# Result table (Unicode-bordered: heavy header, light rows, 6-char status col)
# --------------------------------------------------------------------------- #

STATUS_CELL = {PASS: "PASS  ", FAIL: "FAIL  ", WARN: "WARN  ", SKIP: "SKIP  "}


def _vis_len(s: str) -> int:
    """Display width that counts an emoji + its trailing space as 2 cells.

    The snail emoji renders ~2 columns wide in a monospace terminal. Counting
    it as 2 keeps the light-rule borders aligned with the header.
    """
    width = 0
    for ch in s:
        width += 2 if ord(ch) > 0x2300 else 1
    return width


def _pad(s: str, width: int) -> str:
    pad = width - _vis_len(s)
    return s + (" " * pad if pad > 0 else "")


def _clip(s: str, width: int) -> str:
    if _vis_len(s) <= width:
        return s
    # Trim conservatively on raw length then add ellipsis.
    return s[: max(0, width - 1)] + "…"


def render_table(checks: list[Check]) -> str:
    headers = ("Surface", "Name", "Status", "Description")
    surf_w = max([len(headers[0])] + [_vis_len(c.surface) for c in checks])
    name_w = min(max([len(headers[1])] + [_vis_len(c.name) for c in checks]), 44)
    stat_w = 6
    desc_w = min(max([len(headers[3])] + [_vis_len(c.description) for c in checks]), 62)

    def row(c0: str, c1: str, c2: str, c3: str, v: str) -> str:
        return (
            v + _pad(c0, surf_w) + v + _pad(c1, name_w) + v + _pad(c2, stat_w) + v + _pad(c3, desc_w) + v
        )

    def hline(left: str, junc: str, right: str, ch: str) -> str:
        return left + ch * surf_w + junc + ch * name_w + junc + ch * stat_w + junc + ch * desc_w + right

    out: list[str] = []
    out.append(hline("┏", "┳", "┓", "━"))
    out.append(row(headers[0], headers[1], headers[2], headers[3], "┃"))
    out.append(hline("┡", "╇", "┩", "━"))
    for c in checks:
        out.append(
            row(
                _clip(c.surface, surf_w),
                _clip(c.name, name_w),
                STATUS_CELL.get(c.status, c.status.ljust(stat_w)),
                _clip(c.description, desc_w),
                "│",
            )
        )
    out.append(hline("└", "┴", "┘", "─"))
    return "\n".join(out)


def summary_counts(checks: list[Check]) -> dict[str, int]:
    counts = {PASS: 0, FAIL: 0, WARN: 0, SKIP: 0}
    for c in checks:
        counts[c.status] = counts.get(c.status, 0) + 1
    return counts


