/** A provider answering every POST with a certain 402 (and the JSON models list on GET, a live provider). Counts the POSTs. */
async function creditServer(): Promise<{ url: string; posts: () => number }> {
  let posts = 0;
  server = createServer((req, res) => {
    if (req.method === "GET") {
      res.writeHead(200, { "Content-Type": "application/json" });
      res.end(JSON.stringify({ data: [] }));
      return;
    }
    req.resume();
    req.on("end", () => {
      posts++;
      res.writeHead(402, { "Content-Type": "application/json" });
      res.end(JSON.stringify({ error: { message: "Insufficient credits. Add more using https://openrouter.ai/settings/credits", code: 402 } }));
    });
  });
  await new Promise<void>((r) => server!.listen(0, "127.0.0.1", r));
  return { url: `http://127.0.0.1:${(server!.address() as { port: number }).port}`, posts: () => posts };
}

function redirectFetchTo(base: string): void {
  const realFetch = globalThis.fetch;
  vi.spyOn(globalThis, "fetch").mockImplementation((input: unknown, init?: RequestInit) => realFetch(`${base}${new URL(String(input instanceof Request ? input.url : input)).pathname}`, init));
}

/** One run of the chain walk under a mass_scout usage context, twice in the SAME context: both errors, the stderr text and the POST counts. */
async function runTwice(ready: boolean, brokenCache = false): Promise<{ errors: Error[]; stderr: string; postsAfter: number[] }> {
  fixture(ready, brokenCache);
  const s = await creditServer();
  redirectFetchTo(s.url);
  vi.resetModules();
  const idx = await import("./index.js");
  await idx.boot();
  const validated = await import("./benchmark/validated.js");
  validated.setValidationBypassForTests(true);
  const { ctxStore } = await import("./usage-history.js");
  const spy = vi.spyOn(process.stderr, "write").mockImplementation(() => true);
  const ctx = { tool: "mass_scout", params: "", project: "/tmp", opId: "op-00000000" };
  const caught = (p: Promise<unknown>) => p.then(() => new Error("resolved"), (e: unknown) => e as Error);
  const errors: Error[] = [];
  const postsAfter: number[] = [];
  for (let i = 0; i < 2; i++) {
    errors.push(await ctxStore.run(ctx, () => caught(idx.__ensembleStreamingForTests([{ role: "user", content: "Say hello." }], {}, {}))));
    postsAfter.push(s.posts());
  }
  const stderr = spy.mock.calls.map((c) => String(c[0])).join("");
  // WHY restore here: a second run in the same test would otherwise wrap THIS fetch spy, whose realFetch points at this run's
  // server (closed below); every request of that run then hit a closed port and the test hung past 120 s (measured).
  vi.restoreAllMocks();
  server?.closeAllConnections();
  server?.close();
  server = undefined;
  return { errors, stderr, postsAfter };
}

describe("TRDD-WSPV40Y5: a ready local profile with no calibrated sizing for the tool changes nothing (LocalFallbackNotReady)", () => {
  it("mass_scout over a certain 402: the same verdict as with NO local profile, no fallback line, no latch", async () => {
    const withLocal = await runTwice(true);
    const without = await runTwice(false);
    for (const run of [without, withLocal]) {
      expect(run.errors[0].message).not.toBe("resolved");
      expect(run.stderr).not.toMatch(/local fallback|answered locally|failed too/);
    }
    // The verdict is unchanged: same error type and message as when no local profile exists at all.
    expect(withLocal.errors.map((e) => [e.name, e.message])).toEqual(without.errors.map((e) => [e.name, e.message]));
    // No latch: the second call of the SAME command reaches the remote again, exactly as many times as without a local profile.
    expect(withLocal.postsAfter[0]).toBeGreaterThan(0);
    expect(withLocal.postsAfter[1]).toBeGreaterThan(withLocal.postsAfter[0]);
    expect(withLocal.postsAfter).toEqual(without.postsAfter);
  }, 120_000);

  it("TRDD-PN0N4290 N1: the give-up window is NOT armed on a branch with no local fallback site (the paid modelOverride of high_quality_scan), and is on the chain walk (control, same ready fixture)", async () => {
    fixture(true);
    const s = await creditServer();
    redirectFetchTo(s.url);
    vi.resetModules();
    const idx = await import("./index.js");
    await idx.boot();
    const validated = await import("./benchmark/validated.js");
    validated.setValidationBypassForTests(true);
    const { ctxStore } = await import("./usage-history.js");
    vi.spyOn(process.stderr, "write").mockImplementation(() => true);
    // An expired seeded clock makes both dispatches end at once without a request; only whether the window was built is read.
    const run = (clock: RetryClock, options: { modelOverride?: string }) =>
      ctxStore.run({ tool: "chat", params: "", project: "/tmp", opId: "op-00000000" }, () => idx.__ensembleStreamingForTests([{ role: "user", content: "Say hello." }], options, clock).then(() => undefined, () => undefined));
    const pinned: RetryClock = { startedAt: Date.now() - 10, expired: true };
    await run(pinned, { modelOverride: "vendor/paid-head" });
    expect(pinned.networkGiveUp, "the pinned paid model throws a static exhaustion and never falls back: no window").toBeUndefined();
    const walked: RetryClock = { startedAt: Date.now() - 10, expired: true };
    await run(walked, {});
    expect(walked.networkGiveUp, "the chain walk reaches tryLocalFallback: window armed").toBeDefined();
    const freeOverride: RetryClock = { startedAt: Date.now() - 10, expired: true };
    await run(freeOverride, { modelOverride: "vendor/free-x:free" });
    expect(freeOverride.networkGiveUp, "a :free override rotates through callSingleWithFreeRotation, a fallback site: window armed").toBeDefined();
  }, 120_000);
  it("TRDD-WSPV40Y5 F3: a filesystem error while resolving the local target (EISDIR on the model cache ref) leaves the original verdict, one stderr line per failed call", async () => {
    const broken = await runTwice(true, true);
    const without = await runTwice(false);
    expect(broken.errors[0].message).not.toBe("resolved");
    // The caller's own verdict, never the fs error: identical to the run with no local profile at all.
    expect(broken.errors.map((e) => [e.name, e.message])).toEqual(without.errors.map((e) => [e.name, e.message]));
    expect(broken.errors.map((e) => e.message).join("\n")).not.toMatch(/EISDIR/);
    // Never silent: one line per call that tried the target (nothing is latched), each naming the cause.
    const lines = broken.stderr.split("\n").filter((l) => l.includes("the local fallback target could not be determined"));
    expect(lines).toHaveLength(2);
    expect(lines[0]).toContain("EISDIR");
  }, 120_000);

  it("TRDD-WSPV40Y5 F2: the window that index.ts builds does NOT arm for a tool with no task kind (mass_scout: the send would be refused), and does for chat (control, same ready fixture)", async () => {
    fixture(true);
    const s = await creditServer();
    redirectFetchTo(s.url);
    vi.resetModules();
    const idx = await import("./index.js");
    await idx.boot();
    const validated = await import("./benchmark/validated.js");
    validated.setValidationBypassForTests(true);
    const { ctxStore } = await import("./usage-history.js");
    vi.spyOn(process.stderr, "write").mockImplementation(() => true);
    const clock: RetryClock = { startedAt: Date.now() - 10, expired: true };
    await ctxStore.run({ tool: "chat", params: "", project: "/tmp", opId: "op-00000000" }, () => idx.__ensembleStreamingForTests([{ role: "user", content: "Say hello." }], {}, clock).then(() => undefined, () => undefined));
    expect(clock.networkGiveUp, "a paid remote active profile gets a window").toBeDefined();
    // WHY restore: the fetch redirect would send the strict probe to the credit server, whose 200 JSON models list is a genuine provider answer and vetoes the window.
    vi.restoreAllMocks();
    const closed = createServer();
    await new Promise<void>((r) => closed.listen(0, "127.0.0.1", r));
    const { port } = closed.address() as { port: number };
    await new Promise<void>((r) => closed.close(() => r()));
    const url = `http://127.0.0.1:${port}/v1/chat/completions`;
    const refused = Object.assign(new Error("fetch failed"), { failure: { networkCode: "ECONNREFUSED" } });
    const armUnder = (tool: string) => ctxStore.run({ tool, params: "", project: "/tmp", opId: "op-00000000" }, () => clock.networkGiveUp!.arm(refused, url));
    expect(await armUnder("chat"), "control: calibrated sizing for chat").toBe(true);
    expect(await armUnder("mass_scout"), "no task kind: sizing is null, the window stays unarmed").toBe(false);
  }, 120_000);
});
