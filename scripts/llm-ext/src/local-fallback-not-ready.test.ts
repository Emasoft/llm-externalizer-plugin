/** A provider answering every POST with a certain 402 (and the JSON models list on GET, a live provider). Counts the POSTs. */
async function creditServer(): Promise<{ url: string; posts: () => number }> {
  let posts = 0;
  server = createServer((req, res) => {
    if (req.method === "GET") {
      res.writeHead(200, { "Content-Type": "application/json" });
      res.end(JSON.stringify({ data: [] }));
      return;
    }
    req.resume();
    req.on("end", () => {
      posts++;
      res.writeHead(402, { "Content-Type": "application/json" });
      res.end(JSON.stringify({ error: { message: "Insufficient credits. Add more using https://openrouter.ai/settings/credits", code: 402 } }));
    });
  });
  await new Promise<void>((r) => server!.listen(0, "127.0.0.1", r));
  return { url: `http://127.0.0.1:${(server!.address() as { port: number }).port}`, posts: () => posts };
}

function redirectFetchTo(base: string): void {
  const realFetch = globalThis.fetch;
  vi.spyOn(globalThis, "fetch").mockImplementation((input: unknown, init?: RequestInit) => realFetch(`${base}${new URL(String(input instanceof Request ? input.url : input)).pathname}`, init));
}

/** One run of the chain walk under a mass_scout usage context, twice in the SAME context: both errors, the stderr text and the POST counts. */
async function runTwice(ready: boolean): Promise<{ errors: Error[]; stderr: string; postsAfter: number[] }> {
  fixture(ready);
  const s = await creditServer();
  redirectFetchTo(s.url);
  vi.resetModules();
  const idx = await import("./index.js");
  await idx.boot();
  const validated = await import("./benchmark/validated.js");
  validated.setValidationBypassForTests(true);
  const { ctxStore } = await import("./usage-history.js");
  const spy = vi.spyOn(process.stderr, "write").mockImplementation(() => true);
  const ctx = { tool: "mass_scout", params: "", project: "/tmp", opId: "op-00000000" };
  const caught = (p: Promise<unknown>) => p.then(() => new Error("resolved"), (e: unknown) => e as Error);
  const errors: Error[] = [];
  const postsAfter: number[] = [];
  for (let i = 0; i < 2; i++) {
    errors.push(await ctxStore.run(ctx, () => caught(idx.__ensembleStreamingForTests([{ role: "user", content: "Say hello." }], {}, {}))));
    postsAfter.push(s.posts());
  }
  const stderr = spy.mock.calls.map((c) => String(c[0])).join("");
  // WHY restore here: a second run in the same test would otherwise wrap THIS fetch spy, whose realFetch points at this run's
  // server (closed below); every request of that run then hit a closed port and the test hung past 120 s (measured).
  vi.restoreAllMocks();
  server?.closeAllConnections();
  server?.close();
  server = undefined;
  return { errors, stderr, postsAfter };
}

describe("TRDD-WSPV40Y5: a ready local profile with no calibrated sizing for the tool changes nothing (LocalFallbackNotReady)", () => {
  it("mass_scout over a certain 402: the same verdict as with NO local profile, no fallback line, no latch", async () => {
    const withLocal = await runTwice(true);
    const without = await runTwice(false);
    for (const run of [without, withLocal]) {
      expect(run.errors[0].message).not.toBe("resolved");
      expect(run.stderr).not.toMatch(/local fallback|answered locally|failed too/);
    }
    // The verdict is unchanged: same error type and message as when no local profile exists at all.
    expect(withLocal.errors.map((e) => [e.name, e.message])).toEqual(without.errors.map((e) => [e.name, e.message]));
    // No latch: the second call of the SAME command reaches the remote again, exactly as many times as without a local profile.
    expect(withLocal.postsAfter[0]).toBeGreaterThan(0);
    expect(withLocal.postsAfter[1]).toBeGreaterThan(withLocal.postsAfter[0]);
    expect(withLocal.postsAfter).toEqual(without.postsAfter);
  }, 120_000);
});
