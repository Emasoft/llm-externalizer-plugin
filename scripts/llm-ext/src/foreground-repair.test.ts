function tempDir(kind: string): string {
  const d = mkdtempSync(join("/tmp", `fgrepair-${kind}-`));
  created.push(d);
  return d;
}

const FREE_YAML = `active: free
allow_paid_models: true
profiles:
  # <-- do not touch, generated by llm-ext -->
  free:
    mode: remote
    api: openrouter-remote
    free_only: true
    free_models: [vendor/free-a:free]
    model: vendor/free-a:free
    api_key: "sk-test-fake-openrouter-key"
`;
const FREE_YAML_REPAIRED = FREE_YAML.replace("[vendor/free-a:free]", "[vendor/free-b:free, vendor/free-a:free]");

type UpdaterMode =
  | "success" // changes the profile + stamps lastBenchmarkAt
  | "stamp-only" // stamps success but leaves the profile unchanged
  | "fail" // books a failure (failCount 1 + backoff), like recordBenchmarkFailure
  | "silent"; // records nothing

/** A marker child playing the updater: writes `flag` on start, applies `mode`, holds its lock for holdMs. */
function installMarker(flag: string, holdMs: number, mode: UpdaterMode): void {
  const dir = tempDir("marker");
  marker.script = join(dir, "marker.js");
  const dyn = `{ version: 1, profiles: { free: { lastBenchmarkAt: Date.now(), poolFingerprint: "x", modelIds: [], failCount: 0 } } }`;
  const failed = `{ version: 1, profiles: { free: { lastBenchmarkAt: 0, poolFingerprint: "", modelIds: [], failCount: 1, cooldownUntil: Date.now() + 900000 } } }`;
  const body =
    mode === "success"
      ? `fs.writeFileSync(path.join(cfg, "settings.yaml"), ${JSON.stringify(FREE_YAML_REPAIRED)});\nfs.writeFileSync(path.join(cfg, "dynamic-profiles-state.json"), JSON.stringify(${dyn}));`
      : mode === "stamp-only"
        ? `fs.writeFileSync(path.join(cfg, "dynamic-profiles-state.json"), JSON.stringify(${dyn}));`
        : mode === "fail"
          ? `fs.writeFileSync(path.join(cfg, "default-profiles-state.json"), JSON.stringify(${failed}));`
          : "";
  writeFileSync(
    marker.script,
    `const fs = require("node:fs");
const path = require("node:path");
const cfg = process.env.LLM_EXT_CONFIG_DIR;
fs.writeFileSync(${JSON.stringify(flag)}, "x");
${body}
setTimeout(() => process.exit(0), ${holdMs});
`,
  );
}

/** `respond` decides each POST; it sees whether the updater child has run. */
async function startServer(respond: () => [number, string] | "ok") {
  let posts = 0;
  server = createServer((req, res) => {
    if (req.method === "GET") {
      res.writeHead(404, { "Content-Type": "application/json" });
      res.end("{}");
      return;
    }
    req.on("data", () => {});
    req.on("end", () => {
      posts++;
      const a = respond();
      if (a === "ok") {
        res.writeHead(200, { "Content-Type": "application/json" });
        res.end(
          JSON.stringify({
            model: "vendor/free-a:free",
            choices: [{ message: { role: "assistant", content: "REPAIRED-ANSWER" }, finish_reason: "stop" }],
            usage: { prompt_tokens: 1, completion_tokens: 1, total_tokens: 2 },
          }),
        );
        return;
      }
      res.writeHead(a[0], { "Content-Type": "application/json" });
      res.end(JSON.stringify({ error: { message: a[1] } }));
    });
  });
  await new Promise<void>((r) => server!.listen(0, "127.0.0.1", r));
  const addr = server!.address();
  if (typeof addr !== "object" || addr === null) throw new Error("no address");
  const url = `http://127.0.0.1:${addr.port}`;
  const realFetch = globalThis.fetch;
  vi.spyOn(globalThis, "fetch").mockImplementation((_i: unknown, init?: RequestInit) =>
    realFetch(`${url}/v1/chat/completions`, init),
  );
  return { posts: () => posts };
}

async function loadFreshIndex(yaml: string) {
  const cfgDir = tempDir("cfg");
  writeFileSync(join(cfgDir, "settings.yaml"), yaml, "utf-8");
  writeFileSync(
    join(cfgDir, "catalog-cache.json"),
    JSON.stringify({
      fetchedAtMs: Date.now(),
      models: [
        { id: "vendor/free-a:free", pricing: { prompt: "0", completion: "0" } },
        { id: "vendor/free-b:free", pricing: { prompt: "0", completion: "0" } },
        { id: "vendor/paid-head", pricing: { prompt: "0.0000005", completion: "0.0000005" } },
      ],
    }),
    "utf-8",
  );
  const prevCfg = process.env.LLM_EXT_CONFIG_DIR;
  const prevBai = process.env.BAI_API_KEY;
  delete process.env.BAI_API_KEY;
  process.env.LLM_EXT_CONFIG_DIR = cfgDir;
  vi.resetModules();
  const idx = await import("./index.js");
  await idx.boot();
  return {
    idx,
    cfgDir,
    cleanup: () => {
      if (prevCfg === undefined) delete process.env.LLM_EXT_CONFIG_DIR;
      else process.env.LLM_EXT_CONFIG_DIR = prevCfg;
      if (prevBai !== undefined) process.env.BAI_API_KEY = prevBai;
    },
  };
}

function scanArgs() {
  const folder = tempDir("folder");
  writeFileSync(join(folder, "a.txt"), "hello world\n", "utf-8");
  return { folder_path: folder, instructions: "find bugs", output_dir: tempDir("out") };
}
const chatArgs = () => ({ instructions: "Say hello.", output_dir: tempDir("out") });
const textOf = (r: { content: Array<{ text?: string }> }) => r.content.map((c) => c.text ?? "").join("\n");

describe("foreground repair of a generated profile whose every model failed (TRDD-5Q79QZM7 scope 2)", () => {
  it("repair recorded as success AND the profile changed, single-request tool: the same request is retried once and returns a result", async () => {
    const flag = join(tempDir("flag"), "updated");
    installMarker(flag, 500, "success");
    // The provider is broken until the updater child has run -- the repair is what fixes it.
    const srv = await startServer(() => (existsSync(flag) ? "ok" : [404, "No endpoints found"]));
    const { idx, cleanup } = await loadFreshIndex(FREE_YAML);
    try {
      const r = await idx.dispatchCallTool("chat", chatArgs());
      expect(r.isError, textOf(r)).not.toBe(true);
      // chat saves its answer to a report file and returns the path.
      expect(readFileSync(textOf(r).trim().split("\n")[0], "utf-8")).toContain("REPAIRED-ANSWER");
      expect(srv.posts(), "one failing walk, then exactly one retried request").toBe(2);
    } finally {
      cleanup();
    }
  }, 60_000);

  it("a FAILED update (failure booked): honest 'the update failed' line, retry-later text, NO retry", async () => {
    installMarker(join(tempDir("flag"), "updated"), 300, "fail");
    const srv = await startServer(() => [404, "No endpoints found"]);
    const { idx, cleanup } = await loadFreshIndex(FREE_YAML);
    try {
      const r = await idx.dispatchCallTool("chat", chatArgs());
      expect(r.isError).toBe(true);
      expect(textOf(r)).toContain("no model of the 'free' profile is working right now");
      expect(textOf(r)).toMatch(/Foreground repair was tried and failed: the update failed/);
      expect(srv.posts(), "no retry after a failed update").toBe(1);
    } finally {
      cleanup();
    }
  }, 60_000);

  it("an update that succeeded but left the profile unchanged: no retry, and the line says why", async () => {
    installMarker(join(tempDir("flag"), "updated"), 300, "stamp-only");
    const srv = await startServer(() => [404, "No endpoints found"]);
    const { idx, cleanup } = await loadFreshIndex(FREE_YAML);
    try {
      const r = await idx.dispatchCallTool("chat", chatArgs());
      expect(r.isError).toBe(true);
      expect(textOf(r)).toContain(dynamicProfileRetryLaterMessage("free"));
      expect(textOf(r)).toContain("the profile content did not change, so the request was not retried");
      expect(srv.posts()).toBe(1);
    } finally {
      cleanup();
    }
  }, 60_000);

  it("a multi-item tool (scan_folder) is NOT re-run whole: one line says the profile was repaired and to re-run the failed files", async () => {
    const flag = join(tempDir("flag"), "updated");
    installMarker(flag, 300, "success");
    const srv = await startServer(() => (existsSync(flag) ? "ok" : [404, "No endpoints found"]));
    const { idx, cleanup } = await loadFreshIndex(FREE_YAML);
    try {
      const r = await idx.dispatchCallTool("scan_folder", scanArgs());
      expect(r.isError).toBe(true);
      expect(textOf(r)).toContain(dynamicProfileRetryLaterMessage("free"));
      expect(textOf(r)).toContain("was repaired in the foreground");
      expect(textOf(r)).toContain("re-run the failed files");
      expect(srv.posts(), "the tool was not run a second time").toBe(1);
    } finally {
      cleanup();
    }
  }, 60_000);

  it("the repair exceeds the limit: the retry-later text plus one line saying the foreground repair stopped, no retry", async () => {
    process.env.LLM_EXT_FOREGROUND_REPAIR_TIMEOUT_MS = "300";
    installMarker(join(tempDir("flag"), "updated"), 4_000, "silent");
    const srv = await startServer(() => [404, "No endpoints found"]);
    const { idx, cleanup } = await loadFreshIndex(FREE_YAML);
    try {
      const t0 = Date.now();
      const r = await idx.dispatchCallTool("chat", chatArgs());
      const text = textOf(r);
      expect(r.isError).toBe(true);
      expect(text).toContain(dynamicProfileRetryLaterMessage("free"));
      expect(text).toMatch(/Foreground repair was tried and stopped: the update was still running after \d+ s/);
      expect(Date.now() - t0, "bounded by the limit, not by the update").toBeLessThan(3_500);
      expect(srv.posts()).toBe(1);
    } finally {
      cleanup();
    }
  }, 60_000);

  it("a key error (401) and a paid credit error (402) keep their verdicts: no foreground repair line, no update", async () => {
    const flag = join(tempDir("flag"), "updated");
    installMarker(flag, 300, "success");
    await startServer(() => [401, "User not found"]);
    const first = await loadFreshIndex(FREE_YAML);
    try {
      const r = await first.idx.dispatchCallTool("scan_folder", scanArgs());
      expect(r.isError).toBe(true);
      expect(textOf(r)).not.toContain(dynamicProfileRetryLaterMessage("free"));
      expect(textOf(r)).not.toContain("Foreground repair");
    } finally {
      first.cleanup();
    }
    server?.close();
    vi.restoreAllMocks();
    await startServer(() => [402, "Insufficient credits"]);
    const paid = await loadFreshIndex(`active: paid
allow_paid_models: true
profiles:
  # <-- do not touch, generated by llm-ext -->
  paid:
    mode: remote
    api: openrouter-remote
    model: vendor/paid-head
    api_key: "sk-test-fake-openrouter-key"
`);
    try {
      // The IRON RULE validation gate would refuse the unvalidated paid model before any request (as in profile-chain-402).
      const validated = await import("./benchmark/validated.js");
      validated.setValidationBypassForTests(true);
      const r = await paid.idx.dispatchCallTool("scan_folder", scanArgs()).finally(() => validated.setValidationBypassForTests(false));
      expect(r.isError).toBe(true);
      expect(textOf(r)).toMatch(/credit exhausted/i);
      expect(textOf(r)).not.toContain("Foreground repair");
    } finally {
      paid.cleanup();
    }
  }, 60_000);
});

describe("waitForProfileUpdate waits on the recorded OUTCOME, not on the lock (spawn race)", () => {
  async function inFreshConfigDir<T>(fn: (cfgDir: string) => Promise<T>): Promise<T> {
    const cfgDir = tempDir("wait-cfg");
    const prev = process.env.LLM_EXT_CONFIG_DIR;
    process.env.LLM_EXT_CONFIG_DIR = cfgDir;
    try {
      return await fn(cfgDir);
    } finally {
      if (prev === undefined) delete process.env.LLM_EXT_CONFIG_DIR;
      else process.env.LLM_EXT_CONFIG_DIR = prev;
    }
  }

  it("lock not held (child has not taken it / already gone) and no outcome: NOT ok -- 'ended without recording a result'", async () => {
    await inFreshConfigDir(async () => {
      const base = takeUpdateBaseline("free");
      base.sinceMs -= 10_000; // past the no-result grace
      const r = await waitForProfileUpdate("free", { state: "started" }, base);
      expect(r).toEqual({ ok: false, failed: true, why: "the update ended without recording a result" });
    });
  });

  it("an outcome stamped AFTER the baseline, with the lock free, is a success; one stamped BEFORE it is not", async () => {
    await inFreshConfigDir(async (cfgDir) => {
      const stamp = (at: number) =>
        writeFileSync(
          join(cfgDir, "dynamic-profiles-state.json"),
          JSON.stringify({ version: 1, profiles: { free: { lastBenchmarkAt: at, poolFingerprint: "x", modelIds: [], failCount: 0 } } }),
        );
      const base = takeUpdateBaseline("free");
      stamp(base.sinceMs - 5_000);
      const old = { ...base, sinceMs: base.sinceMs - 10_000 };
      expect(await waitForProfileUpdate("free", { state: "started" }, old)).toMatchObject({ ok: true });
      stamp(base.sinceMs - 60_000);
      const stale = await waitForProfileUpdate("free", { state: "started" }, { ...base, sinceMs: base.sinceMs - 10_000 });
      expect(stale).toMatchObject({ ok: false, failed: true });
      setTimeout(() => stamp(Date.now()), 200);
      expect(await waitForProfileUpdate("free", { state: "running" }, takeUpdateBaseline("free"))).toEqual({ ok: true });
    });
  });

  it("the limit env var: default 10 minutes, a positive number overrides, junk falls back to the default", () => {
    expect(DEFAULT_FOREGROUND_REPAIR_TIMEOUT_MS).toBe(600_000);
    expect(parseForegroundRepairTimeoutMs(undefined)).toBe(600_000);
    expect(parseForegroundRepairTimeoutMs("1500")).toBe(1500);
    expect(parseForegroundRepairTimeoutMs("-5")).toBe(600_000);
    expect(parseForegroundRepairTimeoutMs("abc")).toBe(600_000);
  });
});