      expect(fallbackToLocalErrors(s.fallback_to_local, s.profiles, MAC.platform, MAC.arch)).toEqual([]);
      expect(fallbackToLocalSetting(s, MAC.platform, MAC.arch)).toEqual({ enabled: true, profile: "my_mlx" });
