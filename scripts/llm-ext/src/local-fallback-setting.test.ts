async function closedPortUrl(): Promise<string> {
  const s = createServer();
  await new Promise<void>((r) => s.listen(0, "127.0.0.1", r));
  const { port } = s.address() as { port: number };
  await new Promise<void>((r) => s.close(() => r()));
  return `http://127.0.0.1:${port}`;
}

async function resetServer(): Promise<string> {
  const server = createServer();
  server.on("connection", (socket) => socket.resetAndDestroy());
  servers.push(server);
  await new Promise<void>((r) => server.listen(0, "127.0.0.1", r));
  return `http://127.0.0.1:${(server.address() as { port: number }).port}`;
}

/** Every fetch of the run goes to `base`, keeping its path (the pattern of local-fallback-dispatch.test.ts). */
function redirectFetchTo(base: string): void {
  const realFetch = globalThis.fetch;
  vi.spyOn(globalThis, "fetch").mockImplementation((input: unknown, init?: RequestInit) => realFetch(`${base}${new URL(String(input instanceof Request ? input.url : input)).pathname}`, init));
}

