/**
 * TRDD-M4KERGEF round trip: every settings.yaml writer (all funnel into benchmark/pick.ts writeSettingsAtomic, which re-serialises
 * the parsed YAML Document) keeps the `fallback_to_local` section unchanged. WHY: a writer that dropped it would silently turn a
 * user's `enabled: false` or pin back into the automatic default. Same writer matrix as settings-keep-or-jev.test.ts.
 */
describe("every settings.yaml writer keeps fallback_to_local unchanged (load, write, reload)", () => {
  const SECTION_LINES = ["# keep me: no local model on this laptop", "fallback_to_local:", "  enabled: false", "  profile: my_llama"];
  const MARKED_FREE = [`  # ${GENERATED_MARKER}`, "  free:", "    mode: remote", "    api: openrouter-remote", "    free_only: true", "    free_models: [a/one:free]", "    model: a/one:free", "    api_key: $OPENROUTER_API_KEY"];
  const INVALID_FREE = MARKED_FREE.map((l) => (l === "    mode: remote" ? "    mode: remote-ensemble" : l));
  const UNMARKED_FREE = ["  free:", "    mode: remote", "    api: openrouter-remote", "    free_only: true", "    free_models: [hand/made:free]", "    model: hand/made:free", "    api_key: $OPENROUTER_API_KEY"];
  const MINE = ["  mine:", "    profile-type: paid", "    mode: remote", "    api: openrouter-remote", "    api_key: $OPENROUTER_API_KEY", "    model: vendor/mine"];
  const file = (free: string[]) => ["# my header", "active: free", ...SECTION_LINES, "profiles:", ...free, ...MINE, ...MY_LLAMA, ""].join("\n");
  const EXPECTED = { enabled: false, profile: "my_llama" };
  let seeded = "";

  beforeEach(() => {
    vi.stubEnv("LLM_EXT_CONFIG_DIR", tempDir("rt"));
    vi.stubEnv("BAI_API_KEY", undefined); // the bai seed step would otherwise rewrite the free section
    vi.stubEnv("OPENROUTER_API_KEY", "test-openrouter-key-not-a-real-one"); // ubs:ignore (test fixture): a credential gap is not a regeneration trigger
    for (const step of localProfileStepIds()) markMigrationStepApplied(step);
  });
  const seed = (free: string[] = MARKED_FREE): void => {
    seeded = file(free);
    writeFileSync(getSettingsPath(), seeded, "utf-8");
    expect(loaded().fallback_to_local, "the seed loads with the section").toEqual(EXPECTED);
  };
  function expectSectionKept(): void {
    const text = readFileSync(getSettingsPath(), "utf-8");
    expect(text, "the writer really wrote: a no-op cannot pass").not.toBe(seeded);
    expect((parseYaml(text) as { fallback_to_local?: unknown }).fallback_to_local).toEqual(EXPECTED);
    expect(text).toContain("# keep me: no local model on this laptop");
    const s = loaded();
    expect(s.fallback_to_local).toEqual(EXPECTED);
    expect(fallbackToLocalSetting(s)).toEqual(EXPECTED);
  }
  const pick = (modelId: string) => ({ modelId, meanF1: 1, actualCost: 0, latencyMs: 1, inputDollarsPerMillion: 0, outputDollarsPerMillion: 0 });
  const aProfile = (over: Record<string, unknown>): Profile => ({ ...unpopulatedDefaultProfile("free"), ...over }) as Profile;

  const cases: Array<[string, string[], () => unknown]> = [
    ["writeDynamicProfileSection (rewrite free)", MARKED_FREE, () => writeDynamicProfileSection(getSettingsPath(), "free", (cur) => aProfile({ ...cur, free_models: ["b/two:free"], model: "b/two:free" }), { notify: () => {} })],
    ["writeDynamicProfileSection (create paid)", MARKED_FREE, () => writeDynamicProfileSection(getSettingsPath(), "paid", () => unpopulatedDefaultProfile("paid"), { notify: () => {} })],
    ["writeDynamicUserKeys", MARKED_FREE, () => writeDynamicUserKeys(getSettingsPath(), "free", (cur) => ({ ...(cur as Profile), selection: "first" }) as Profile)],
    ["dropKeysOutsideClosedSet", [...MARKED_FREE, "    stray_key: 1"], () => dropKeysOutsideClosedSet(getSettingsPath(), "free")],
    ["regenerateInvalidMarkedSection", INVALID_FREE, () => regenerateInvalidMarkedSection({ name: "free", settingsPath: getSettingsPath(), current: (parseYaml(readFileSync(getSettingsPath(), "utf-8")) as { profiles: Record<string, Profile> }).profiles.free, nowMs: Date.now() })],
    ["migrateProfileSections", UNMARKED_FREE, () => { let stamp: number | undefined; return migrateProfileSections(getSettingsPath(), { notify: () => {}, readStamp: () => stamp, writeStamp: (n) => { stamp = n; return null; } }); }],
    ["migrateSettingsTo141", MARKED_FREE, () => migrateSettingsTo141(getSettingsPath(), { notify: () => {}, isApplied: isMigrationStepApplied, markApplied: markMigrationStepApplied })],
    ["applyPicksToSettings", MARKED_FREE, () => applyPicksToSettings(getSettingsPath(), "mine", [pick("vendor/new")])],
    ["applyEnsembleSlotToSettings", MARKED_FREE, () => applyEnsembleSlotToSettings(getSettingsPath(), "mine", "model", "vendor/other")],
    ["applyToolModelToSettings", MARKED_FREE, () => applyToolModelToSettings(getSettingsPath(), "mine", registeredTools()[0], "vendor/tool")],
    ["applyFreePoolToSettings", MARKED_FREE, () => applyFreePoolToSettings(getSettingsPath(), "mine", ["x/y:free"])],
    ["addProfileToSettings", MARKED_FREE, () => addProfileToSettings(getSettingsPath(), "added", { mode: "remote", api: "openrouter-remote", model: "v/a", api_key: "$OPENROUTER_API_KEY" })],
  ];
  for (const [name, free, write] of cases) {
    it(`${name} keeps the section`, () => {
      seed(free);
      write();
      expectSectionKept();
    });
  }
});
