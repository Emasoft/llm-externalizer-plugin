/**
 * TRDD-I6KUI1X6: after a boot whose settings load THROWS, no settings.yaml writer may persist the generated default document the boot catch returns.
 *
 * Why this is a real risk: the boot IIFE catch in index.ts hands out generateDefaultSettings() as the in-memory document, and its default `free` is
 * an invalid placeholder. repairInvalidActiveGeneratedProfile used to take that in-memory `free` as the profile to repair, so on a file that became
 * readable again (a transient read error) it would back up and rewrite the user's marked `free` section from a document that was never read from
 * disk. The writers below are driven in-process after a real failed boot; settings.yaml must be byte-identical (or still a directory) and no
 * settings* sibling (backup, tmp file, lock) may appear. The throw is real, not mocked: settings.yaml is a directory (EISDIR) or an unreadable
 * file (chmod 000, EACCES; ensureSettingsExist backs up and regenerates an UNPARSEABLE file, so only a read error reaches the catch).
 * Pattern: boot-failed-settings.test.ts. Temp dirs carry the `llm-ext-` prefix. No network: the maintainer gets a catalog fetcher that fails the test if called.
 * Not driven here: the detached profile detector / updater children (they write JSON state and reach settings.yaml only through writeDynamicProfileSection, which re-reads disk under the lock).
 */

import { describe, it, expect, vi, afterEach, beforeEach } from "vitest";
import { chmodSync, mkdtempSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

process.env.LLM_EXT_INSTALL_RULE = "0";

// Windows has no /tmp (see boot-failed-settings.test.ts); elsewhere keep the literal /tmp the config-dir allowlist names.
const TMP_BASE = process.platform === "win32" ? tmpdir() : "/tmp";
const CANNOT_MAKE_UNREADABLE = process.platform === "win32" || (typeof process.getuid === "function" && process.getuid() === 0);

// A user's marked generated `free` section that fails validation (copied from parallel-repair.test.ts): the exact bytes an unguarded repair
// from the in-memory default `free` would back up and replace.
const INVALID_MARKED_FREE = [
  "active: free",
  "profiles:",
  "  # <-- do not touch, generated by llm-ext -->",
  "  free:",
  "    mode: remote",
  "    api: openrouter-remote",
  "    free_only: true",
  "    free_models: [only/one:free, only/two:free]",
  "    model: only/one:free",
  "    api_key: $OPENROUTER_API_KEY",
  "    tool_models:",
  "      scan_folder: vendor/paid-model",
  "",
].join("\n");

const created: string[] = [];
let prevCfgDir: string | undefined;
let prevKey: string | undefined;

beforeEach(() => {
  // regenerateInvalidMarkedSection answers "not-applicable" for a section whose key is unset (credential gap); a fake key keeps an unguarded repair able to write.
  prevKey = process.env.OPENROUTER_API_KEY;
  process.env.OPENROUTER_API_KEY = "test-openrouter-key-not-a-real-one";
});

afterEach(() => {
  if (prevCfgDir === undefined) delete process.env.LLM_EXT_CONFIG_DIR;
  else process.env.LLM_EXT_CONFIG_DIR = prevCfgDir;
  prevCfgDir = undefined;
  if (prevKey === undefined) delete process.env.OPENROUTER_API_KEY;
  else process.env.OPENROUTER_API_KEY = prevKey;
  for (const dir of created.splice(0)) rmSync(dir, { recursive: true, force: true });
});

async function bootWith(prepare: (settingsPath: string) => void) {
  const cfgDir = mkdtempSync(join(TMP_BASE, "llm-ext-i6kui1x6-"));
  created.push(cfgDir);
  const settingsPath = join(cfgDir, "settings.yaml");
  prepare(settingsPath);
  prevCfgDir = process.env.LLM_EXT_CONFIG_DIR;
  process.env.LLM_EXT_CONFIG_DIR = cfgDir;
  vi.resetModules();
  const idx = await import("./index.js");
  const maintainer = await import("./dynamic-maintainer.js");
  await idx.boot();
  expect(idx.__getBootStateForTests()).toEqual({ settingsValid: false, activeResolved: false });
  return { idx, maintainer, cfgDir, settingsPath };
}

function textOf(result: { content: Array<{ text?: string }> }): string {
  return result.content.map((c) => c.text ?? "").join("\n");
}

function settingsSiblings(cfgDir: string): string[] {
  return readdirSync(cfgDir).filter((n) => n.startsWith("settings")).sort();
}

async function runMaintainer(maintainer: typeof import("./dynamic-maintainer.js")): Promise<{ wrote: boolean; fetches: number }> {
  let fetches = 0;
  const wrote = await maintainer.maintainDynamicProfiles({
    fetchCatalog: async () => {
      fetches++;
      throw new Error("the test never uses the network");
    },
    log: () => {},
  });
  return { wrote, fetches };
}

async function driveGuardedWriters(idx: typeof import("./index.js")): Promise<void> {
  for (const [name, source] of [["free", "default"], ["free", "flag"], ["paid", "flag"], ["local", "flag"]] as const) {
    const result = idx.overrideActiveProfile(name, source);
    expect(result.ok, `${name}/${source}`).toBe(false);
    if (!result.ok) expect(result.error).toContain("Failed to load settings");
  }
  const folder = mkdtempSync(join(TMP_BASE, "llm-ext-i6kui1x6-scan-"));
  created.push(folder);
  writeFileSync(join(folder, "a.txt"), "hello world\n", "utf-8");
  const r = await idx.dispatchCallTool("scan_folder", { folder_path: folder, instructions: "find bugs" });
  const text = textOf(r);
  expect(r.isError, text).toBe(true);
  expect(text).toContain("NOT CONFIGURED");
  // The inline repair of a marked generated profile must not even be attempted from the default document.
  expect(text).not.toContain("Inline repair");
}

describe("TRDD-I6KUI1X6 — no settings.yaml writer persists the default document after a failed boot load", () => {
  it("settings.yaml is a directory: override, dispatch repair path and the maintainer pass write nothing", async () => {
    const { idx, maintainer, cfgDir, settingsPath } = await bootWith((p) => mkdirSync(p));
    const before = settingsSiblings(cfgDir);
    expect(before).toEqual(["settings.yaml"]);
    await driveGuardedWriters(idx);
    const m = await runMaintainer(maintainer);
    expect(m).toEqual({ wrote: false, fetches: 0 });
    expect(statSync(settingsPath).isDirectory()).toBe(true);
    expect(readdirSync(settingsPath)).toEqual([]);
    expect(settingsSiblings(cfgDir)).toEqual(before);
  });

  it.skipIf(CANNOT_MAKE_UNREADABLE)("settings.yaml is an unreadable file that becomes readable again: the user's marked section is never rewritten from the defaults", async () => {
    const { idx, maintainer, cfgDir, settingsPath } = await bootWith((p) => {
      writeFileSync(p, INVALID_MARKED_FREE, "utf-8");
      chmodSync(p, 0o000);
    });
    // Still unreadable: the maintainer reads the file itself (loadSettings -> null) and must stop before any write or fetch.
    const m = await runMaintainer(maintainer);
    expect(m).toEqual({ wrote: false, fetches: 0 });
    // The transient error is over: the file is readable and carries an invalid marked `free` section. The process still holds the default document.
    chmodSync(settingsPath, 0o600);
    await driveGuardedWriters(idx);
    expect(readFileSync(settingsPath, "utf-8")).toBe(INVALID_MARKED_FREE);
    expect(settingsSiblings(cfgDir)).toEqual(["settings.yaml"]);
  });

  it("control: the repair writer does rewrite a marked invalid section when handed the default `free` as current, so the boot-failure guard is what protects the file", async () => {
    const cfgDir = mkdtempSync(join(TMP_BASE, "llm-ext-i6kui1x6-ctl-"));
    created.push(cfgDir);
    const settingsPath = join(cfgDir, "settings.yaml");
    writeFileSync(settingsPath, INVALID_MARKED_FREE, "utf-8");
    prevCfgDir = process.env.LLM_EXT_CONFIG_DIR;
    process.env.LLM_EXT_CONFIG_DIR = cfgDir;
    vi.resetModules();
    const { regenerateInvalidMarkedSection } = await import("./dynamic-maintainer.js");
    const { generateDefaultSettings } = await import("./config.js");
    const outcome = regenerateInvalidMarkedSection({ name: "free", settingsPath, current: generateDefaultSettings().profiles.free, nowMs: Date.now() });
    expect(outcome.kind).toBe("regenerated");
    expect(readFileSync(settingsPath, "utf-8")).not.toBe(INVALID_MARKED_FREE);
  });
});
