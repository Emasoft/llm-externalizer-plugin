const ENSEMBLE_MODELS = ["vendor/m-one", "vendor/m-two", "vendor/m-three"];

/** A node:http server for a remote-ensemble profile: `respond` decides each POST (200 answer, an error status with a body, or never). */
async function startEnsembleServer(respond: (model: string, nth: number) => { status: number; delayMs?: number } | "hang") {
  const seen: string[] = [];
  const counts = new Map<string, number>();
  const srv = createServer((req, res) => {
    if (req.method !== "POST") {
      res.writeHead(404, { "Content-Type": "application/json" });
      res.end("{}");
      return;
    }
    const chunks: Buffer[] = [];
    req.on("data", (c) => chunks.push(c));
    req.on("end", () => {
      const model = (JSON.parse(Buffer.concat(chunks).toString("utf-8")) as { model: string }).model;
      const nth = (counts.get(model) ?? 0) + 1;
      counts.set(model, nth);
      seen.push(model);
      const verdict = respond(model, nth);
      if (verdict === "hang") return;
      setTimeout(() => {
        if (verdict.status !== 200) {
          res.writeHead(verdict.status, { "Content-Type": "application/json" });
          res.end(JSON.stringify({ error: { message: `model '${model}' not found` } }));
          return;
        }
        res.writeHead(200, { "Content-Type": "application/json" });
        res.end(JSON.stringify({ id: "c", model, choices: [{ index: 0, message: { role: "assistant", content: `answer from ${model}` }, finish_reason: "stop" }], usage: { prompt_tokens: 1, completion_tokens: 1, total_tokens: 2 } }));
      }, verdict.delayMs ?? 0);
    });
  });
  servers.push(srv);
  await new Promise<void>((resolve) => srv.listen(0, "127.0.0.1", resolve));
  const addr = srv.address();
  if (typeof addr !== "object" || addr === null) throw new Error("server address unavailable");
  // Decimal form of 127.0.0.1: the URL parser reaches the loopback server while config.ts isLocalUrl sees a remote host, which a remote-ensemble profile requires.
  return { url: `http://2130706433:${addr.port}`, seen: () => [...seen] };
}

