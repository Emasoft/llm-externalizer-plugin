const CLI = join(dirname(fileURLToPath(import.meta.url)), "..", "dist", "llm-ext.js");

/** The real CLI over a throwaway HOME and config dir, on a remote-ensemble profile reaching `url`. */
function runCli(url: string, files: string[], extra: string[]): Promise<{ code: number | null; stdout: string; stderr: string; ms: number }> {
  const cfgDir = tempDir("cfg");
  const homeDir = tempDir("home");
  writeFileSync(join(cfgDir, "settings.yaml"), ensembleYaml(url), "utf-8");
  const out = tempDir("out");
  const started = Date.now();
  return new Promise((resolvePromise) => {
    const child = spawn(process.execPath, [CLI, "llm", "ask", "--input_files_paths", files.join(","), "--instructions", "find bugs", "-o", out, ...extra], {
      stdio: ["ignore", "pipe", "pipe"],
      // TMPDIR: whatever temp directory the CLI makes for itself lands in a directory this test removes, not in the shared /tmp.
      env: { ...process.env, HOME: homeDir, TMPDIR: tempDir("tmp"), LLM_EXT_CONFIG_DIR: cfgDir, LLM_EXT_INSTALL_RULE: "0", LLM_EXT_DISABLE_AUTO_RECONCILE: "1", LLM_EXT_DISABLE_DEFAULT_PROFILE_POPULATION: "1" },
    });
    let stdout = "";
    let stderr = "";
    child.stdout.on("data", (c: Buffer) => (stdout += c.toString()));
    child.stderr.on("data", (c: Buffer) => (stderr += c.toString()));
    // SIGKILL guard: a process that will not leave on its own is the failure under test.
    const guard = setTimeout(() => child.kill("SIGKILL"), 90_000);
    child.on("exit", (code) => {
      clearTimeout(guard);
      resolvePromise({ code, stdout, stderr, ms: Date.now() - started });
    });
  });
}

function twoFiles(): string[] {
  const folder = tempDir("cli-files");
  return ["a.txt", "b.txt"].map((n) => {
    writeFileSync(join(folder, n), `${n}\n`, "utf-8");
    return join(folder, n);
  });
}

