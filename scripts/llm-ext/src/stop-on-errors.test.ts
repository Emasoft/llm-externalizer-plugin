/** HEAD answers `headStatus` after `headDelayMs`; every other model answers 200. */
async function startServer(headStatus: number, headDelayMs = 0) {
  const models: string[] = [];
  server = createServer((req, res) => {
    if (req.method === "GET") {
      res.writeHead(404, { "Content-Type": "application/json" });
      res.end("{}");
      return;
    }
    const chunks: Buffer[] = [];
    req.on("data", (c) => chunks.push(c));
    req.on("end", () => {
      const model = (JSON.parse(Buffer.concat(chunks).toString("utf-8")) as { model: string }).model;
      models.push(model);
      const send = (): void => {
        if (model === HEAD && headStatus !== 200) {
          res.writeHead(headStatus, { "Content-Type": "application/json" });
          res.end(JSON.stringify({ error: { message: `model '${model}' not found` } }));
          return;
        }
        res.writeHead(200, { "Content-Type": "application/json" });
        res.end(JSON.stringify({ id: "c", model, choices: [{ index: 0, message: { role: "assistant", content: `answer from ${model}` }, finish_reason: "stop" }], usage: { prompt_tokens: 1, completion_tokens: 1, total_tokens: 2 } }));
      };
      if (model === HEAD && headDelayMs > 0) setTimeout(send, headDelayMs);
      else send();
    });
  });
  await new Promise<void>((resolve) => server!.listen(0, "127.0.0.1", resolve));
  const addr = server.address();
  if (typeof addr !== "object" || addr === null) throw new Error("server address unavailable");
  return { url: `http://127.0.0.1:${addr.port}`, models: () => [...models] };
}

