describe("which failures --stop_on_errors acts on (TRDD-SWNIIFTF, USER decision: not found, no response, 5xx, credit)", () => {
  /** A fresh command-stop.ts and http.ts with the flag on, then `fn` over the real stopIfStopOnErrors. */
  async function withFlag<T>(fn: (m: { stopIfStopOnErrors: (model: string, failure: unknown, endpointDead?: boolean) => void; attachFailure: (e: Error, f: { status?: number; networkCode?: string }) => void; stop: typeof import("./command-stop.js"); idx: typeof import("./index.js") }) => T): Promise<T> {
    vi.resetModules();
    const stop = await import("./command-stop.js");
    stop.enableStopOnErrors();
    const http = await import("./provider/http.js");
    const idx = await import("./index.js");
    return fn({ stopIfStopOnErrors: http.stopIfStopOnErrors, attachFailure: http.attachFailure, stop, idx });
  }
  const typed = (attach: (e: Error, f: { status?: number; networkCode?: string }) => void, status: number | undefined, networkCode?: string): Error => {
    const e = new Error(status === undefined ? "fetch failed" : `API error ${status} (openrouter): upstream said so`);
    attach(e, { status, networkCode });
    return e;
  };

  it("(g) not found, no response, a server error and a credit failure stop the command", async () => {
    const cases: Array<[number | undefined, string | undefined]> = [[404, undefined], [410, undefined], [503, undefined], [402, undefined], [undefined, "ECONNREFUSED"]];
    for (const [status, networkCode] of cases) {
      await withFlag(({ stopIfStopOnErrors, attachFailure, stop }) => {
        expect(() => stopIfStopOnErrors("vendor/m", typed(attachFailure, status, networkCode)), `status ${status} code ${networkCode}`).toThrow();
        expect(stop.isCommandStopped()).toBe(true);
        expect(stop.commandStopExitCode()).toBe(6);
      });
    }
  });

  it("(h) a failure VALUE (the free rotation's text) is read by its status: 404 stops, 429 does not", async () => {
    await withFlag(({ stopIfStopOnErrors, stop }) => {
      expect(() => stopIfStopOnErrors("vendor/m:free", "API error 429 (openrouter): rate limited")).not.toThrow();
      expect(stop.isCommandStopped()).toBe(false);
      expect(() => stopIfStopOnErrors("vendor/m:free", "API error 404 (openrouter): no such model")).toThrow();
      expect(stop.isCommandStopped()).toBe(true);
    });
  });

  it("(i) a 413, a 429, an IRON RULE refusal and a breaker verdict do not stop the command", async () => {
    await withFlag(({ stopIfStopOnErrors, attachFailure, stop, idx }) => {
      const refusals: unknown[] = [
        typed(attachFailure, 413),
        typed(attachFailure, 429),
        new Error("IRON RULE: model vendor/m is not validated for chat; run its benchmark first"),
        new idx.ServiceAbortError("SERVER ISSUE DETECTED: 3 of the last 3 requests failed (service overloaded)"),
      ];
      for (const refusal of refusals) expect(() => stopIfStopOnErrors("vendor/m", refusal)).not.toThrow();
      expect(stop.isCommandStopped()).toBe(false);
    });
  });
});

