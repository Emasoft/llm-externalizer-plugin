// The b.ai-only boot exemption (P6b-fix4 B1), plus a 14.1-C2a-FOLLOWUP
// exhaustion-handling case (a pinned-model failure). The third case, "a held
// bench lock is waited for, bounded by its TTL", was deleted with D2: no
// command waits for a profile update any more (waitForHeldBenchLock is gone).
//
// TRDD-OE27RD7I 14.1-C2a-FOLLOWUP: this file used to ALSO cover the dispatch
// pre-flight's synchronous "maintainer write + digest + reload" sequence
// (P6b-fix4 Q2 / S-4') with three cases (CONTROL, (d), (e)). C2b-wire
// (commit a6fec0c/5842393) replaced that synchronous in-process maintainer
// call with a detached, fire-and-forget detector (index.ts's dispatch
// pre-flight now calls `spawnDetachedDetector` and awaits nothing) — a
// command is a short-lived process and the MCP server is gone, so "reload on
// a concurrent detector write mid-dispatch" stopped being a live requirement:
// the NEXT command reads whatever the detector/updater eventually wrote. All
// three of those cases now failed (verified: 3/4 red on HEAD, exactly the
// three whose subject is the removed synchronous mechanism) and were
// deleted rather than patched — there is nothing left on the dispatch path
// for them to observe.
//
// The b.ai case survives untouched (still green) because its subject is
// different and still live: a benchmark child's write, on a b.ai-only
// machine, produces a settings.yaml a SECOND boot accepts (the missing-key
// exemption must not flip off just because the section stopped looking
// unpopulated). That never depended on the dispatch pre-flight being
// synchronous — it drives three real, separately-spawned CLI processes and
// asserts on the file each one leaves behind, independent of whichever
// mechanism (detector+updater now, the old in-process maintainer before)
// performed the write in between.
//
// The case below it is about the modelOverride branch's exhaustion sentence.
// It needs a real dispatch against a controlled settings.yaml (same
// loadFreshIndex recipe honest-402.test.ts / default-profile-wiring.test.ts
// already use: index.ts reads settings once at module import, so a FRESH
// re-import per scenario is how a test gets its own settings.yaml read
// instead of racing this file's other cases over one shared module
// instance).

