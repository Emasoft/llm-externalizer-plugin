/** A provider that resets every connection (its GET /v1/models too): ECONNRESET is retried for ~31 s without the 1b window, so only an armed window ends it fast. */
async function resetServer(): Promise<string> {
  server = createServer();
  server.on("connection", (socket) => socket.resetAndDestroy());
  await new Promise<void>((r) => server!.listen(0, "127.0.0.1", r));
  return `http://127.0.0.1:${(server!.address() as { port: number }).port}`;
}

