async function closedPortUrl(): Promise<string> {
  const s = createServer();
  await new Promise<void>((r) => s.listen(0, "127.0.0.1", r));
  const { port } = s.address() as { port: number };
  await new Promise<void>((r) => s.close(() => r()));
  return `http://127.0.0.1:${port}`;
}

/** A provider answering every POST with `status` (and the JSON models list on GET, a live provider). Counts the POSTs. */
async function statusServer(status: number, message: string): Promise<{ url: string; posts: () => number }> {
  let posts = 0;
  server = createServer((req, res) => {
    if (req.method === "GET") {
      res.writeHead(200, { "Content-Type": "application/json" });
      res.end(JSON.stringify({ data: [] }));
      return;
    }
    req.resume();
    req.on("end", () => {
      posts++;
      res.writeHead(status, { "Content-Type": "application/json" });
      res.end(JSON.stringify({ error: { message, code: status } }));
    });
  });
  await new Promise<void>((r) => server!.listen(0, "127.0.0.1", r));
  return { url: `http://127.0.0.1:${(server!.address() as { port: number }).port}`, posts: () => posts };
}

/** Every fetch of the run goes to `base`, keeping its path (the strict probe's GET /v1/models included). */
function redirectFetchTo(base: string): void {
  const realFetch = globalThis.fetch;
  vi.spyOn(globalThis, "fetch").mockImplementation((input: unknown, init?: RequestInit) => realFetch(`${base}${new URL(String(input instanceof Request ? input.url : input)).pathname}`, init));
}

