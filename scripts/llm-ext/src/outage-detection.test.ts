function tempDir(kind: string): string {
  const d = mkdtempSync(join("/tmp", `outage-${kind}-`));
  created.push(d);
  return d;
}

const yamlWith = (models: string[]) => `active: free
allow_paid_models: true
profiles:
  # <-- do not touch, generated by llm-ext -->
  free:
    mode: remote
    api: openrouter-remote
    free_only: true
    free_models: [${models.join(", ")}]
    model: ${models[0]}
    api_key: "sk-test-fake-openrouter-key"
`;

/** A marker child that only records that the updater ran, then holds the lock briefly. */
function installMarker(flag: string): void {
  const dir = tempDir("marker");
  marker.script = join(dir, "marker.js");
  writeFileSync(marker.script, `require("node:fs").writeFileSync(${JSON.stringify(flag)}, "x");\nsetTimeout(() => process.exit(0), 300);\n`);
}

/** `statusOf(model)` is the status every POST for that model gets; `probeStatus` is what the provider reachability probe (GET /v1/models) gets, 0 = connection dropped. */
async function startServer(statusOf: (model: string) => number, probeStatus = 200) {
  let posts = 0;
  server = createServer((req, res) => {
    if (req.method === "GET") {
      if (probeStatus === 0) {
        req.socket.destroy();
        return;
      }
      res.writeHead(probeStatus, { "Content-Type": "application/json" });
      res.end("{}");
      return;
    }
    let body = "";
    req.on("data", (c) => (body += c));
    req.on("end", () => {
      posts++;
      const model = (JSON.parse(body) as { model?: string }).model ?? "";
      const status = statusOf(model);
      res.writeHead(status, { "Content-Type": "application/json" });
      res.end(JSON.stringify({ error: { message: status === 404 ? "No endpoints found" : "Service unavailable" } }));
    });
  });
  await new Promise<void>((r) => server!.listen(0, "127.0.0.1", r));
  const addr = server!.address();
  if (typeof addr !== "object" || addr === null) throw new Error("no address");
  const url = `http://127.0.0.1:${addr.port}`;
  const realFetch = globalThis.fetch;
  vi.spyOn(globalThis, "fetch").mockImplementation((_i: unknown, init?: RequestInit) => realFetch(`${url}/v1/chat/completions`, init));
  return { posts: () => posts };
}

async function loadFreshIndex(yaml: string, models: string[]) {
  const cfgDir = tempDir("cfg");
  writeFileSync(join(cfgDir, "settings.yaml"), yaml, "utf-8");
  writeFileSync(
    join(cfgDir, "catalog-cache.json"),
    JSON.stringify({ fetchedAtMs: Date.now(), models: models.map((id) => ({ id, pricing: { prompt: "0", completion: "0" } })) }),
    "utf-8",
  );
  const prevCfg = process.env.LLM_EXT_CONFIG_DIR;
  const prevBai = process.env.BAI_API_KEY;
  delete process.env.BAI_API_KEY;
  process.env.LLM_EXT_CONFIG_DIR = cfgDir;
  vi.resetModules();
  const idx = await import("./index.js");
  await idx.boot();
  return {
    idx,
    cleanup: () => {
      if (prevCfg === undefined) delete process.env.LLM_EXT_CONFIG_DIR;
      else process.env.LLM_EXT_CONFIG_DIR = prevCfg;
      if (prevBai !== undefined) process.env.BAI_API_KEY = prevBai;
    },
  };
}

const chatArgs = () => ({ instructions: "Say hello.", output_dir: tempDir("out") });
const textOf = (r: { content: Array<{ text?: string }> }) => r.content.map((c) => c.text ?? "").join("\n");
const A = "vendor/free-a:free";
const B = "vendor/free-b:free";

describe("provider-wide outage detection (TRDD-5Q79QZM7 scope 3)", () => {
  it("two models both 504 and the provider probe fails: honest outage message naming the provider and the status, no update requested, no wait", async () => {
    process.env.LLM_EXT_FOREGROUND_REPAIR_TIMEOUT_MS = "30000";
    const flag = join(tempDir("flag"), "updated");
    installMarker(flag);
    await startServer(() => 504, 503);
    const { idx, cleanup } = await loadFreshIndex(yamlWith([A, B]), [A, B]);
    try {
      const t0 = Date.now();
      const r = await idx.dispatchCallTool("chat", chatArgs());
      const text = textOf(r);
      expect(r.isError).toBe(true);
      expect(text).toContain("OpenRouter appears to be down or unreachable");
      expect(text).toContain("observed: 504");
      expect(text).toContain("retry in a few minutes");
      expect(text).not.toContain("change the profile");
      expect(text).not.toContain(dynamicProfileRetryLaterMessage("free"));
      expect(text).not.toContain("Foreground repair");
      expect(existsSync(flag), "no profile update was started").toBe(false);
      expect(Date.now() - t0, "no foreground wait").toBeLessThan(25_000);
    } finally {
      cleanup();
    }
  }, 60_000);

  it("one model 504 and one 404: not an outage, the normal repair path runs", async () => {
    process.env.LLM_EXT_FOREGROUND_REPAIR_TIMEOUT_MS = "300";
    const flag = join(tempDir("flag"), "updated");
    installMarker(flag);
    await startServer((m) => (m === A ? 504 : 404));
    const { idx, cleanup } = await loadFreshIndex(yamlWith([A, B]), [A, B]);
    try {
      const r = await idx.dispatchCallTool("chat", chatArgs());
      expect(r.isError).toBe(true);
      expect(textOf(r)).not.toContain("appears to be down");
      expect(textOf(r)).toContain(dynamicProfileRetryLaterMessage("free"));
      await vi.waitFor(() => expect(existsSync(flag), "the profile update was started").toBe(true), { timeout: 10_000 }); // the detached child may start after the 300 ms wait
    } finally {
      cleanup();
    }
  }, 60_000);

  it("a single model failing 504: not enough evidence for an outage, the normal repair path runs", async () => {
    process.env.LLM_EXT_FOREGROUND_REPAIR_TIMEOUT_MS = "300";
    const flag = join(tempDir("flag"), "updated");
    installMarker(flag);
    await startServer(() => 504);
    const { idx, cleanup } = await loadFreshIndex(yamlWith([A]), [A, B]);
    try {
      const r = await idx.dispatchCallTool("chat", chatArgs());
      expect(r.isError).toBe(true);
      expect(textOf(r)).not.toContain("appears to be down");
      expect(textOf(r)).toContain(dynamicProfileRetryLaterMessage("free"));
      await vi.waitFor(() => expect(existsSync(flag), "the profile update was started").toBe(true), { timeout: 10_000 }); // the detached child may start after the 300 ms wait
    } finally {
      cleanup();
    }
  }, 60_000);

  it("two models both 504 but the provider probe is reachable: the models are broken, not the provider, so the normal repair path runs", async () => {
    process.env.LLM_EXT_FOREGROUND_REPAIR_TIMEOUT_MS = "300";
    const flag = join(tempDir("flag"), "updated");
    installMarker(flag);
    await startServer(() => 504, 200);
    const { idx, cleanup } = await loadFreshIndex(yamlWith([A, B]), [A, B]);
    try {
      const r = await idx.dispatchCallTool("chat", chatArgs());
      expect(r.isError).toBe(true);
      expect(textOf(r)).not.toContain("appears to be down");
      expect(textOf(r)).toContain(dynamicProfileRetryLaterMessage("free"));
      await vi.waitFor(() => expect(existsSync(flag), "the profile update was started").toBe(true), { timeout: 10_000 }); // the detached child may start after the 300 ms wait
    } finally {
      cleanup();
    }
  }, 60_000);

  it("two models both 504 and the probe connection is dropped: outage (a network error counts as unreachable)", async () => {
    process.env.LLM_EXT_FOREGROUND_REPAIR_TIMEOUT_MS = "300";
    const flag = join(tempDir("flag"), "updated");
    installMarker(flag);
    await startServer(() => 504, 0);
    const { idx, cleanup } = await loadFreshIndex(yamlWith([A, B]), [A, B]);
    try {
      const r = await idx.dispatchCallTool("chat", chatArgs());
      expect(textOf(r)).toContain("OpenRouter appears to be down or unreachable");
      expect(existsSync(flag)).toBe(false);
    } finally {
      cleanup();
    }
  }, 60_000);

  // A 503 is retried for the whole 5-minute window (RETRY_DEADLINE_MS is a plain constant, no env knob), so the dispatch tests
  // above use 504 (3-try budget) to reach the same exhaustion; the 503 and the other cause shapes are covered on the detector.
  describe("detectProviderOutage on typed causes", () => {
    const OR = "https://openrouter.ai/api";
    const cause = (status: number | undefined, modelId: string | undefined, baseUrl: string | undefined, networkCode?: string) => {
      const e = new Error(status === undefined ? "fetch failed" : `API error ${status} (openrouter): x`);
      attachFailure(e, { status, networkCode, modelId, baseUrl });
      return e;
    };

    it("two distinct models on one provider, both 503: suspected, naming the provider and the statuses", async () => {
      const { idx, cleanup } = await loadFreshIndex(yamlWith([A, B]), [A, B]);
      try {
        expect(idx.detectProviderOutage([cause(503, A, OR), cause(503, B, OR)])).toEqual({ baseUrl: OR, observed: ["503"] });
        expect(idx.detectProviderOutage([cause(503, A, OR), cause(undefined, B, OR, "ECONNRESET")])).toEqual({ baseUrl: OR, observed: ["503", "ECONNRESET"] });
      } finally {
        cleanup();
      }
    });

    it("the same model failing twice is one model's evidence: not an outage", async () => {
      const { idx, cleanup } = await loadFreshIndex(yamlWith([A, B]), [A, B]);
      try {
        expect(idx.detectProviderOutage([cause(503, A, OR), cause(503, A, OR)])).toBeUndefined();
      } finally {
        cleanup();
      }
    });

    it("causes from different providers are never merged: not an outage", async () => {
      const { idx, cleanup } = await loadFreshIndex(yamlWith([A, B]), [A, B]);
      try {
        expect(idx.detectProviderOutage([cause(503, A, OR), cause(503, B, "https://api.b.ai")])).toBeUndefined();
      } finally {
        cleanup();
      }
    });

    it("a 404 among the causes, an untyped cause, or a cause with no recorded model: not an outage", async () => {
      const { idx, cleanup } = await loadFreshIndex(yamlWith([A, B]), [A, B]);
      try {
        expect(idx.detectProviderOutage([cause(503, A, OR), cause(404, B, OR)])).toBeUndefined();
        expect(idx.detectProviderOutage([cause(503, A, OR), new Error("API error 503 (openrouter): x")])).toBeUndefined();
        expect(idx.detectProviderOutage([cause(503, A, OR), cause(503, undefined, undefined)])).toBeUndefined();
      } finally {
        cleanup();
      }
    });
  });
});