// TRDD-5Q79QZM7 acceptance box 4: settings.yaml is backed up before each write
// and two parallel repairs never both write. The write lock is a cross-process
// file lock, so this spawns two REAL node processes that run
// regenerateInvalidMarkedSection against the same invalid marked free section,
// released together by a start-gate file.

import { describe, it, expect, afterAll } from "vitest";
import { spawn } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { parse } from "yaml";

const HERE = dirname(fileURLToPath(import.meta.url));
const MAINTAINER = resolve(HERE, "dynamic-maintainer.ts");

const INVALID_MARKED_FREE = [
  "active: free",
  "profiles:",
  "  # <-- do not touch, generated by llm-ext -->",
  "  free:",
  "    mode: remote",
  "    api: openrouter-remote",
  "    free_only: true",
  "    free_models: [only/one:free, only/two:free]",
  "    model: only/one:free",
  "    api_key: $OPENROUTER_API_KEY",
  "    tool_models:",
  "      scan_folder: vendor/paid-model",
  "",
].join("\n");

// Child: parse the section from disk, wait for the gate file, run the repair,
// print the outcome as one JSON line.
const CHILD_SOURCE = `
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";
import { regenerateInvalidMarkedSection } from ${JSON.stringify(MAINTAINER)};
const [settingsPath, gate, readyFile] = process.argv.slice(2);
const current = parse(readFileSync(settingsPath, "utf-8")).profiles.free;
writeFileSync(readyFile, "ready");
const sleeper = new Int32Array(new SharedArrayBuffer(4));
while (!existsSync(gate)) Atomics.wait(sleeper, 0, 0, 2);
const out = regenerateInvalidMarkedSection({ name: "free", settingsPath, current, nowMs: Date.now() });
process.stdout.write(JSON.stringify({ kind: out.kind, backupPath: out.backupPath ?? null }) + "\\n");
`;

const created: string[] = [];
afterAll(() => {
  for (const dir of created.splice(0)) rmSync(dir, { recursive: true, force: true });
});

interface ChildResult {
  code: number | null;
  stdout: string;
  stderr: string;
}

function runChild(script: string, args: string[], env: NodeJS.ProcessEnv): Promise<ChildResult> {
  return new Promise((done) => {
    const child = spawn(process.execPath, [script, ...args], { env, stdio: ["ignore", "pipe", "pipe"] });
    let stdout = "";
    let stderr = "";
    child.stdout.on("data", (d) => (stdout += d));
    child.stderr.on("data", (d) => (stderr += d));
    child.on("close", (code) => done({ code, stdout, stderr }));
  });
}

describe("parallel inline repair of one invalid marked section (TRDD-5Q79QZM7)", () => {
  it("two real processes racing: exactly one regenerates and backs up, the other reports placeholder-present, original bytes survive", async () => {
    const work = mkdtempSync(join("/tmp", "llm-ext-parallel-repair-"));
    created.push(work);
    const cfgDir = join(work, "cfg");
    const homeDir = join(work, "home");
    mkdirSync(cfgDir);
    mkdirSync(homeDir);
    const settingsPath = join(cfgDir, "settings.yaml");
    writeFileSync(settingsPath, INVALID_MARKED_FREE, "utf-8");

    const entry = join(work, "child-entry.ts");
    const bundle = join(work, "child.mjs");
    writeFileSync(entry, CHILD_SOURCE, "utf-8");
    await build({
      entryPoints: [entry],
      outfile: bundle,
      bundle: true,
      platform: "node",
      format: "esm",
      external: ["better-sqlite3"],
      banner: { js: 'import { createRequire as __r } from "node:module"; const require = __r(import.meta.url);' },
      // The entry lives in a temp dir with no node_modules: resolve "yaml" from this package.
      nodePaths: [resolve(HERE, "..", "node_modules")],
      logLevel: "silent",
    });

    const env: NodeJS.ProcessEnv = {
      PATH: process.env.PATH,
      HOME: homeDir,
      LLM_EXT_CONFIG_DIR: cfgDir,
      LLM_EXT_INSTALL_RULE: "0",
      OPENROUTER_API_KEY: "test-openrouter-key-not-a-real-one",
    };
    const gate = join(work, "go");
    const readyA = join(work, "ready-a");
    const readyB = join(work, "ready-b");
    const a = runChild(bundle, [settingsPath, gate, readyA], env);
    const b = runChild(bundle, [settingsPath, gate, readyB], env);
    // Release both only once both have loaded and parsed, so they hit the lock together.
    const deadline = Date.now() + 60_000;
    while (!(existsSync(readyA) && existsSync(readyB))) {
      if (Date.now() > deadline) throw new Error("children never became ready");
      await new Promise((r) => setTimeout(r, 10));
    }
    writeFileSync(gate, "go");
    const [ra, rb] = await Promise.all([a, b]);

    expect(ra.code, ra.stderr).toBe(0);
    expect(rb.code, rb.stderr).toBe(0);
    const kinds = [ra, rb].map((r) => (JSON.parse(r.stdout.trim()) as { kind: string }).kind).sort();
    // The loser finds the placeholder the winner wrote: invalid by design, so
    // it is reported as "placeholder-present" (TRDD-5Q79QZM7), never re-backed-up.
    expect(kinds).toEqual(["placeholder-present", "regenerated"]);

    const backupDir = join(cfgDir, "backups");
    const backups = existsSync(backupDir) ? readdirSync(backupDir) : [];
    expect(backups, "exactly one backup").toHaveLength(1);
    expect(backups[0]).toContain("settings-before-regenerate");
    expect(readFileSync(join(backupDir, backups[0]), "utf-8")).toContain("vendor/paid-model");

    const finalText = readFileSync(settingsPath, "utf-8");
    expect(finalText).not.toContain("vendor/paid-model");
    const free = (parse(finalText) as { profiles: { free: Record<string, unknown> } }).profiles.free;
    expect(free.mode).toBe("remote");
  }, 120_000);

  it("a stale placeholder left by an earlier run (no race) is reported as placeholder-present and takes no second backup", async () => {
    const work = mkdtempSync(join("/tmp", "llm-ext-stale-placeholder-"));
    created.push(work);
    const settingsPath = join(work, "settings.yaml");
    writeFileSync(settingsPath, INVALID_MARKED_FREE, "utf-8");
    const { regenerateInvalidMarkedSection } = await import("./dynamic-maintainer.js");
    const current = (parse(INVALID_MARKED_FREE) as { profiles: { free: never } }).profiles.free;

    const first = regenerateInvalidMarkedSection({ name: "free", settingsPath, current, nowMs: Date.now() });
    expect(first.kind).toBe("regenerated");
    // The backup dir is the shared config dir, so compare listings, not counts.
    const firstBackup = (first as { backupPath: string }).backupPath;
    const backupDir = dirname(firstBackup);
    const afterFirst = readdirSync(backupDir).sort();

    // A run that read the section before the first repair now meets the placeholder under the lock.
    const second = regenerateInvalidMarkedSection({ name: "free", settingsPath, current, nowMs: Date.now() + 5000 });
    expect(second.kind).toBe("placeholder-present");
    expect(readdirSync(backupDir).sort(), "no second backup").toEqual(afterFirst);
    expect(readFileSync(firstBackup, "utf-8")).toContain("vendor/paid-model");
  }, 60_000);
});