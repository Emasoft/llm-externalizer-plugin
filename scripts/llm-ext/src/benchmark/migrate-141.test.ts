/**
 * D0 (TRDD-AL8GIZYA) — the 14.1.0 migration list's first step,
 * `price-ceiling-into-paid`. Real files, real YAML, real config dir (a fresh
 * mkdtemp per test): the migration rewrites the user's own settings.yaml, so
 * every test here is about proving it moves the value to the right place
 * exactly once, and refuses (rather than guesses) when it cannot tell which
 * value is authoritative.
 */

import { mkdtempSync, rmSync, writeFileSync, readFileSync, chmodSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "../test-tmp-root.js";
import { parse as parseYaml } from "yaml";

import { migrateSettingsTo141 } from "./pick.js";
import {
  isMigrationStepApplied,
  markMigrationStepApplied,
  readDynamicProfilesState,
  updateDynamicProfileRecord,
} from "../default-profiles-state.js";
import { getSettingsPath, loadSettings, settingsLevelErrors, getEnsemblePriceCeiling } from "../config.js";

import { afterEach, beforeEach, describe, it, expect } from "vitest";

let cfgDir: string;
let prevCfgDir: string | undefined;
let prevBaiKey: string | undefined;
let notices: string[];

beforeEach(() => {
  prevCfgDir = process.env.LLM_EXT_CONFIG_DIR;
  // D5: the bai-reserved-seed step seeds the free section whenever
  // BAI_API_KEY resolves; an ambient key (this project's login shells export
  // one) would rewrite these fixtures' byte-identity assertions by env leg.
  // The seed step's own behaviour is pinned in profile-migration.test.ts.
  prevBaiKey = process.env.BAI_API_KEY;
  delete process.env.BAI_API_KEY;
  cfgDir = mkdtempSync(join(tmpdir(), "lx-migr141-"));
  process.env.LLM_EXT_CONFIG_DIR = cfgDir;
  notices = [];
});

afterEach(() => {
  if (prevCfgDir === undefined) delete process.env.LLM_EXT_CONFIG_DIR;
  else process.env.LLM_EXT_CONFIG_DIR = prevCfgDir;
  if (prevBaiKey === undefined) delete process.env.BAI_API_KEY;
  else process.env.BAI_API_KEY = prevBaiKey;
  rmSync(cfgDir, { recursive: true, force: true });
});

function write(yaml: string): void {
  writeFileSync(getSettingsPath(), yaml, "utf-8");
}

function run(): ReturnType<typeof migrateSettingsTo141> {
  return migrateSettingsTo141(getSettingsPath(), {
    notify: (m) => notices.push(m),
    isApplied: isMigrationStepApplied,
    markApplied: markMigrationStepApplied,
  });
}

const BASE_PROFILES = [
  "profiles:",
  `  # <-- do not touch, generated by llm-ext -->`,
  "  free:",
  "    mode: remote",
  "    api: openrouter-remote",
  "    api_key: $OPENROUTER_API_KEY",
  "    free_only: true",
  "    free_models: []",
  "    model: placeholder/unpopulated-default-profile",
].join("\n");

describe("migrateSettingsTo141 — price-ceiling-into-paid", () => {
  it("moves the top-level ceiling into profiles.paid.selection, deletes the top-level key, and creates the unpopulated paid section through the generated writer", () => {
    write([`ensemble_price_ceiling_usd_per_million: 0.42`, BASE_PROFILES, ""].join("\n"));

    const r = run();
    // D6a added a second step: with no `local` section the rename is a clean
    // no-op that also records, so one run stamps both steps.
    expect(r.applied).toEqual(["price-ceiling-into-paid", "local-detected-providers", "bai-binding-to-reserved-slot", "bai-reserved-seed", "dynamic-unknown-keys", "scouting-section-marked", "or-jev-section-added", "profile-type-written"]);

    const raw = readFileSync(getSettingsPath(), "utf-8");
    expect(raw).not.toContain("ensemble_price_ceiling_usd_per_million:");

    const settings = loadSettings();
    expect(settings?.profiles.paid?.selection?.price_ceiling_usd_per_million).toBe(0.42);
    expect(getEnsemblePriceCeiling(settings)).toBe(0.42);
    // The generated marker + generated keys landed the ordinary way — the
    // paid section is a real, usable dynamic profile, not a bare stub.
    expect(raw).toContain("<-- do not touch, generated by llm-ext -->");
  });

  it("the ceiling moves exactly once — a second run is a no-op, the step stays recorded, and it survives an UNRELATED later state write (readDynamicProfilesState carries migrationsApplied through)", () => {
    write([`ensemble_price_ceiling_usd_per_million: 0.9`, BASE_PROFILES, ""].join("\n"));

    const first = run();
    expect(first.applied).toEqual(["price-ceiling-into-paid", "local-detected-providers", "bai-binding-to-reserved-slot", "bai-reserved-seed", "dynamic-unknown-keys", "scouting-section-marked", "or-jev-section-added", "profile-type-written"]);
    expect(readDynamicProfilesState().migrationsApplied).toEqual([
      "price-ceiling-into-paid",
      "local-detected-providers",
      "bai-binding-to-reserved-slot",
      "bai-reserved-seed",
      "dynamic-unknown-keys",
      "scouting-section-marked",
      "or-jev-section-added",
      "profile-type-written",
    ]);

    const afterFirst = readFileSync(getSettingsPath(), "utf-8");
    notices = [];
    const second = run();
    expect(second.applied).toEqual([]); // no-op: isApplied() short-circuits before any IO
    expect(notices).toEqual([]);
    expect(readFileSync(getSettingsPath(), "utf-8")).toBe(afterFirst);

    // An UNRELATED write to the same state file (the dynamic-profile record
    // updater, called constantly by the maintainer) must not erase the step —
    // this is the exact trap readDynamicProfilesState's docblock warns about:
    // a field dropped on read is a field ERASED on the next write.
    updateDynamicProfileRecord("free", () => ({
      lastBenchmarkAt: 123,
      poolFingerprint: "x",
      modelIds: [],
      failCount: 0,
    }));
    expect(readDynamicProfilesState().migrationsApplied).toEqual([
      "price-ceiling-into-paid",
      "local-detected-providers",
      "bai-binding-to-reserved-slot",
      "bai-reserved-seed",
      "dynamic-unknown-keys",
      "scouting-section-marked",
      "or-jev-section-added",
      "profile-type-written",
    ]);
    expect(isMigrationStepApplied("price-ceiling-into-paid")).toBe(true);
  });

  it("the ambiguous case (top-level and profiles.paid.selection set to DIFFERENT values) leaves the file byte-identical, records nothing, and settingsLevelErrors refuses with E-D3", () => {
    const ambiguous = [
      "ensemble_price_ceiling_usd_per_million: 0.5",
      "profiles:",
      `  # <-- do not touch, generated by llm-ext -->`,
      "  free:",
      "    mode: remote",
      "    api: openrouter-remote",
      "    api_key: $OPENROUTER_API_KEY",
      "    free_only: true",
      "    free_models: []",
      "    model: placeholder/unpopulated-default-profile",
      `  # <-- do not touch, generated by llm-ext -->`,
      "  paid:",
      "    mode: remote",
      "    api: openrouter-remote",
      "    api_key: $OPENROUTER_API_KEY",
      "    model: placeholder/unpopulated-default-profile",
      "    selection:",
      "      price_ceiling_usd_per_million: 0.9",
      "",
    ].join("\n");
    write(ambiguous);

    const r = run();
    expect(r.applied).toEqual([]);
    expect(notices).toEqual([]);
    expect(readFileSync(getSettingsPath(), "utf-8")).toBe(ambiguous);
    expect(isMigrationStepApplied("price-ceiling-into-paid")).toBe(false);

    const settings = loadSettings();
    expect(settings).not.toBeNull();
    const errors = settingsLevelErrors(settings!);
    expect(errors).toHaveLength(1);
    expect(errors[0]).toContain("settings.yaml sets the paid price ceiling twice");
    expect(errors[0]).toContain("top-level 0.5");
    expect(errors[0]).toContain("profiles.paid.selection 0.9");
  });

  it("no top-level key at all is a clean no-op that still records the step, so a settings.yaml that never had it isn't re-inspected forever", () => {
    write([BASE_PROFILES, ""].join("\n"));
    const before = readFileSync(getSettingsPath(), "utf-8");

    const r = run();
    expect(r.applied).toEqual(["price-ceiling-into-paid", "local-detected-providers", "bai-binding-to-reserved-slot", "bai-reserved-seed", "dynamic-unknown-keys", "scouting-section-marked", "or-jev-section-added", "profile-type-written"]);
    // The price-ceiling step moves nothing, so it rewrites nothing. The only changes to the file are the `or-jev` section (PF-04) appended after the last profile and the later `profile-type-written` step adding the `profile-type:` line of the one profile (`free`) BASE_PROFILES holds.
    const after = readFileSync(getSettingsPath(), "utf-8");
    const withoutTypes = after.split("\n").filter((l) => !/^\s+profile-type: /.test(l)).join("\n");
    expect(withoutTypes.startsWith(before)).toBe(true);
    expect(after.split("\n").filter((l) => /^\s+profile-type: /.test(l))).toHaveLength(2); // free (stamped) and or-jev (written with its template)
    expect(isMigrationStepApplied("price-ceiling-into-paid")).toBe(true);
  });

  it("SAME value at both positions is not ambiguous — it migrates normally (idempotent overwrite, top-level deleted)", () => {
    const sameValue = [
      "ensemble_price_ceiling_usd_per_million: 0.7",
      "profiles:",
      `  # <-- do not touch, generated by llm-ext -->`,
      "  free:",
      "    mode: remote",
      "    api: openrouter-remote",
      "    api_key: $OPENROUTER_API_KEY",
      "    free_only: true",
      "    free_models: []",
      "    model: placeholder/unpopulated-default-profile",
      `  # <-- do not touch, generated by llm-ext -->`,
      "  paid:",
      "    mode: remote",
      "    api: openrouter-remote",
      "    api_key: $OPENROUTER_API_KEY",
      "    model: placeholder/unpopulated-default-profile",
      "    selection:",
      "      price_ceiling_usd_per_million: 0.7",
      "",
    ].join("\n");
    write(sameValue);

    const r = run();
    expect(r.applied).toEqual(["price-ceiling-into-paid", "local-detected-providers", "bai-binding-to-reserved-slot", "bai-reserved-seed", "dynamic-unknown-keys", "scouting-section-marked", "or-jev-section-added", "profile-type-written"]);
    const raw = readFileSync(getSettingsPath(), "utf-8");
    expect(raw).not.toContain("ensemble_price_ceiling_usd_per_million:");
    const parsed = parseYaml(raw) as { profiles: { paid: { selection: { price_ceiling_usd_per_million: number } } } };
    expect(parsed.profiles.paid.selection.price_ceiling_usd_per_million).toBe(0.7);
  });

  // D0 fix-up 2 (TRDD-AL8GIZYA): E-D3 used to print "sets the paid price
  // ceiling twice (top-level X, profiles.paid.selection Y)" even when the
  // migration never got to write the paid side at all (settings.yaml
  // read-only) -- Y was `undefined`, and the "twice" claim was false: only
  // ONE position actually holds a value. A chmod 0444 file reproduces the
  // real failure mode (a write error, not a parse/logic error) instead of
  // mocking the fs.
  it("only the top-level ceiling present, and the config dir is read-only (write fails): settingsLevelErrors reports the write-failure message, not a false 'twice' claim, and the file is left byte-identical", () => {
    write([`ensemble_price_ceiling_usd_per_million: 0.42`, BASE_PROFILES, ""].join("\n"));
    const before = readFileSync(getSettingsPath(), "utf-8");
    // WHY chmod the DIRECTORY, not the file: every writer here is an
    // atomic write (write a `.tmp.<pid>` sibling, then rename over the
    // target) -- that needs write permission on the DIRECTORY, and
    // rename(2) does not re-check the target file's own mode bits, so
    // chmod 0444 on settingsPath itself would not have reproduced the
    // failure at all (caught by this test's first attempt, which chmod'd
    // the file and saw the migration succeed anyway).
    chmodSync(cfgDir, 0o555);
    try {
      expect(() => run()).not.toThrow();
      expect(isMigrationStepApplied("price-ceiling-into-paid")).toBe(false);
      expect(readFileSync(getSettingsPath(), "utf-8")).toBe(before);

      const settings = loadSettings();
      expect(settings).not.toBeNull();
      const errors = settingsLevelErrors(settings!);
      expect(errors).toHaveLength(1);
      expect(errors[0]).not.toContain("sets the paid price ceiling twice");
      expect(errors[0]).toContain("still has the top-level ensemble_price_ceiling_usd_per_million");
      expect(errors[0]).toContain("could not write the file");
    } finally {
      chmodSync(cfgDir, 0o755);
    }
  });
});
